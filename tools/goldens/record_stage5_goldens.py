"""Record, or reproduce and compare, the stage-5 golden battery (plan P4-D395 part 5).

USAGE:

    python tools/goldens/record_stage5_goldens.py            # reproduce and compare
    python tools/goldens/record_stage5_goldens.py --write    # record again

`tests/stage5_goldens.py` is GENERATED by `--write` and by nothing else;
it is never edited by hand. Recording again is allowed only in the
commit whose change moves the bytes, and that commit's message and its
landing's plan decision name every case and record that moved, and why
(plan P4-D395 part 5, "RE-RECORDING").

WHAT A RUN DOES, in this order. It imports the product -- every module
of the package and the libraries a run loads -- THEN installs
`tools/provenance/guard_runner.py`'s own audit hook (`install_guard()`),
which refuses network, process and native-call capability for the rest
of the process; it cannot run as that runner's script, because the hook
refuses `ctypes`, which numpy imports (measured, plan P4-D395 Step 0).
Before the battery it makes a NEGATIVE CONTROL under the hook it has
just installed: it imports `socket`, or, where `socket` is loaded
already, opens one, and unless that stops on the guard's own message
(`guard_runner.GUARD_MESSAGE`) the run stops red and records nothing, so
a recorder whose hook is missing cannot pass. Then it runs every
recorded case of `tests/stage5_battery.py` through `cli.main`, the
command line as typed, in a temporary folder of its own, and keeps three
records of each (below). Without `--write` it compares them with
`tests/stage5_goldens.py` and with the three digests stored there, and
exits 1 on any difference, naming each; with `--write` it writes the
module again.

THE THREE RECORDS OF A CASE.
- Each file in the case's folder after the run, by SHA-256, bytes and
  lines, a link by the name it points at.
- The screen as ONE transcript: the characters each stream received, in
  the order made, kept as runs -- an empty write dropped and adjacent
  writes to one stream joined, every change of stream kept -- each run
  by SHA-256, characters and lines. Where a write ends is not a byte a
  person sees: `print("m")` writes "m" and then the line end.
- The exit status: what `cli.main` returned, or the code of the
  `SystemExit` it ended in (before lane S5a, `--help` and the parser's
  refusals ended that way).
The case's folder, as made and as resolved, is replaced by `<FOLDER>`,
and the installed version by `<VERSION>`, in every file and in the
transcript. The environment is fixed for every case: `COLUMNS=80`,
`NO_COLOR=1`, `PYTHON_COLORS=0`, `FORCE_COLOR` unset (argparse wraps its
help at the terminal's width and later Pythons may colour it), and
`os.isatty` answers false, so nobody is asked whatever terminal runs it.
The table floor stays on (`small_tables_refused=True`, the installed
command's own), in the suite as in a fresh interpreter.

WHAT IS COMPARED WHERE. Files and exit statuses on every platform; the
transcript on POSIX alone, because the lines a person types are quoted
for PowerShell on Windows (`cli._quoted_for_the_shell`), and nowhere the
case's folder would itself need quoting; text argparse lays out itself
(`Case.argparse_text`) only on the recorder's Python version, because
each Python's argparse lays it out its own way; the cases that leave a
link at an output's name on POSIX alone. Each skip is named.

No network, no subprocess, no dynamic code: it imports the package,
runs the command in this process and writes one Python file.
"""

from __future__ import annotations

import argparse
import dataclasses
import hashlib
import importlib
import os
import pathlib
import sys
import tempfile
import typing

ROOT = pathlib.Path(__file__).resolve().parents[2]
TARGET = ROOT / "tests" / "stage5_goldens.py"
FOLDER_WORD = "<FOLDER>"
VERSION_WORD = "<VERSION>"
FIXED_ENVIRONMENT = (("COLUMNS", "80"), ("NO_COLOR", "1"), ("PYTHON_COLORS", "0"))
UNSET_ENVIRONMENT = ("FORCE_COLOR",)
OUT = "out"
ERR = "err"

Record = typing.Tuple[object, ...]  # one line of the goldens


class _Transcript:
    """The characters each stream received, kept as runs."""

    def __init__(self) -> None:
        self.runs: "list[tuple[str, list[str]]]" = []

    def write(self, stream: str, text: str) -> None:
        if not text:
            return
        if self.runs and self.runs[-1][0] == stream:
            pieces = self.runs[-1][1]
            pieces += [text]
            return
        self.runs += [(stream, [text])]

    def joined(self) -> "list[tuple[str, str]]":
        return [(stream, "".join(pieces)) for stream, pieces in self.runs]


class _Stream:
    """A text stream feeding one side of a transcript."""

    encoding = "utf-8"
    errors = "surrogateescape"

    def __init__(self, transcript: _Transcript, name: str) -> None:
        self._transcript = transcript
        self._name = name

    def write(self, text: str) -> int:
        self._transcript.write(self._name, f"{text}")
        return len(text)

    def writelines(self, lines: "typing.Iterable[str]") -> None:
        for line in lines:
            self.write(line)

    def flush(self) -> None:
        return None

    def isatty(self) -> bool:
        return False

    def fileno(self) -> int:
        raise OSError("the battery's stream has no file descriptor")


class _NoInput:
    """Standard input that holds nothing and counts every read."""

    encoding = "utf-8"

    def __init__(self) -> None:
        self.reads = 0

    def read(self, *_size: int) -> str:
        self.reads = self.reads + 1
        return ""

    def readline(self, *_size: int) -> str:
        self.reads = self.reads + 1
        return ""

    def isatty(self) -> bool:
        return False

    def fileno(self) -> int:
        raise OSError("the battery's input has no file descriptor")


@dataclasses.dataclass
class Capture:
    """One case's run: its exit status, its transcript, and what strayed.

    ``strays`` is what reached the process's own standard output and
    error while an ``invoke`` given by the caller ran (it is the
    transcript itself when `cli.main` runs), and ``reads`` how many reads
    standard input received.
    """

    exit: int
    runs: "list[tuple[str, str]]"
    strays: "list[tuple[str, str]]"
    reads: int


def _exit_of(code: object) -> int:
    if code is None:
        return 0
    if isinstance(code, int):
        return code
    return 1


def capture(
    argv: "typing.Sequence[str]",
    folder: pathlib.Path,
    invoke: "typing.Callable[[list[str], typing.Callable[[str, str], None]], int] | None" = None,
) -> Capture:
    """Run one command line in ``folder`` and capture what it shows.

    With no ``invoke`` the command runs through `cli.main(argv,
    small_tables_refused=True)` with standard output and error replaced
    by two writers feeding one transcript, and a `SystemExit` it ends in
    is caught and its code kept. With an ``invoke``, the caller runs the
    command itself, handed the transcript's `write(stream, text)` to
    pass on as a screen; the process's own streams then feed ``strays``.
    Either way the environment is fixed, `os.isatty` answers false,
    standard input holds nothing, the working folder is ``folder``, and
    all of it is put back afterwards.
    """
    from synthtwin import cli

    transcript = _Transcript()
    strays = _Transcript()
    nothing = _NoInput()
    saved_streams = (sys.stdout, sys.stderr, sys.stdin)
    saved_isatty = os.isatty
    saved_folder = os.getcwd()
    saved_environment = {
        name: os.environ.get(name)
        for name in [name for name, _value in FIXED_ENVIRONMENT] + list(UNSET_ENVIRONMENT)
    }
    try:
        for name, value in FIXED_ENVIRONMENT:
            os.environ[name] = value
        for name in UNSET_ENVIRONMENT:
            os.environ.pop(name, None)
        os.isatty = _never_a_terminal
        os.chdir(folder)
        sys.stdin = typing.cast(typing.TextIO, nothing)
        if invoke is None:
            sys.stdout = typing.cast(typing.TextIO, _Stream(transcript, OUT))
            sys.stderr = typing.cast(typing.TextIO, _Stream(transcript, ERR))
            try:
                code = _exit_of(cli.main(list(argv), small_tables_refused=True))
            except SystemExit as stop:
                code = _exit_of(stop.code)
        else:
            sys.stdout = typing.cast(typing.TextIO, _Stream(strays, OUT))
            sys.stderr = typing.cast(typing.TextIO, _Stream(strays, ERR))
            code = invoke(list(argv), transcript.write)
    finally:
        sys.stdout, sys.stderr, sys.stdin = saved_streams
        os.isatty = saved_isatty
        os.chdir(saved_folder)
        for name, value in saved_environment.items():
            if value is None:
                os.environ.pop(name, None)
            else:
                os.environ[name] = value
    return Capture(code, transcript.joined(), strays.joined(), nothing.reads)


def _never_a_terminal(_descriptor: int) -> bool:
    return False


def _folder_forms(folder: pathlib.Path) -> "list[str]":
    """The case's folder as made and as resolved, the longer first."""
    forms = sorted({f"{folder}", os.path.realpath(folder)}, key=len, reverse=True)
    return [form for form in forms if form]


def normalised(text: str, folder: pathlib.Path, version: str) -> str:
    """The text with the folder and the version replaced by their words."""
    for form in _folder_forms(folder):
        text = text.replace(form, FOLDER_WORD)
    if version:
        text = text.replace(version, VERSION_WORD)
    return text


def _normalised_bytes(data: bytes, folder: pathlib.Path, version: str) -> bytes:
    for form in _folder_forms(folder):
        data = data.replace(form.encode("utf-8"), FOLDER_WORD.encode("utf-8"))
    if version:
        data = data.replace(version.encode("utf-8"), VERSION_WORD.encode("utf-8"))
    return data


def _digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def records_of(
    case_key: str, folder: pathlib.Path, captured: Capture, version: str
) -> "list[Record]":
    """The case's three records: its exit, its folder's files, its transcript."""
    found: "list[Record]" = [(case_key, "exit", captured.exit)]
    for name in sorted(os.listdir(folder)):
        place = folder / name
        if place.is_symlink():
            found += [(case_key, "link", name, os.path.basename(os.readlink(place)))]
        elif place.is_file():
            data = _normalised_bytes(place.read_bytes(), folder, version)
            found += [(case_key, "file", name, _digest(data), len(data), data.count(b"\n"))]
    for index, (stream, text) in enumerate(captured.runs):
        shown = normalised(text, folder, version)
        found += [
            (
                case_key,
                stream,
                index,
                _digest(shown.encode("utf-8", "surrogatepass")),
                len(shown),
                shown.count("\n"),
            )
        ]
    return found


def _battery() -> typing.Any:
    tests = f"{ROOT / 'tests'}"
    if tests not in sys.path:
        sys.path.insert(0, tests)
    return importlib.import_module("stage5_battery")


def reproduce(
    root: pathlib.Path,
    invoke: "typing.Callable[[list[str], typing.Callable[[str, str], None]], int] | None" = None,
    cases: "typing.Sequence[typing.Any] | None" = None,
) -> "tuple[list[Record], dict[str, Capture]]":
    """Run the recorded cases (or ``cases``) under ``root``; return their records and captures.

    A case marked POSIX-only is not run on Windows. Every other case runs
    in its order, each in its own folder or its base case's.
    """
    from synthtwin import cli

    battery = _battery()
    version = cli._version()
    chosen = battery.RECORDED if cases is None else cases
    found: "list[Record]" = []
    captures: "dict[str, Capture]" = {}
    for case in chosen:
        if case.posix_only and os.name == "nt":
            continue
        folder = battery.lay(case, root)
        captured = capture(case.argv, folder, invoke)
        captures[case.key] = captured
        found += records_of(case.key, folder, captured, version)
    return found, captures


def battery_digest() -> str:
    """The digest of the battery's table of recorded cases."""
    return _digest(repr(_battery().recorded_rows()).encode("utf-8"))


def recorder_digest() -> str:
    """The digest of this file's own source."""
    return _digest(pathlib.Path(__file__).read_bytes())


def records_digest(records: "typing.Sequence[Record]") -> str:
    """The digest of the records, one line each, in order."""
    return _digest("\n".join([repr(record) for record in records]).encode("utf-8"))


def python_version() -> str:
    return f"{sys.version_info[0]}.{sys.version_info[1]}"


def _skipped(record: Record, goldens: typing.Any) -> str:
    """Why a record is not compared on this platform and Python, or ""."""
    battery = _battery()
    cases = {case.key: case for case in battery.RECORDED}
    case = cases.get(f"{record[0]}")
    kind = record[1]
    if case is not None and case.posix_only and os.name == "nt":
        return "a link at an output's name is refused on Windows before anything is written"
    if kind in (OUT, ERR):
        if os.name == "nt":
            return "the lines a person types are quoted for PowerShell on Windows"
        if case is not None and case.argparse_text and python_version() != goldens.RECORDER_PYTHON:
            return f"argparse lays out its own text per Python; recorded on {goldens.RECORDER_PYTHON}"
    return ""


def compare(
    reproduced: "typing.Sequence[Record]", goldens: typing.Any, root: "pathlib.Path | None" = None
) -> "tuple[list[str], list[str]]":
    """The differences between reproduced records and the goldens, and the skips.

    Records are compared by (case, kind, name or index); a record the
    goldens hold that this run did not make, or the reverse, is a
    difference unless it is skipped here. Where ``root`` is given and the
    case's folder would need quoting for a shell, its transcript is
    skipped and the reason named.
    """
    from synthtwin import cli

    def identity(record: Record) -> "tuple[object, ...]":
        return tuple(record[:3]) if record[1] != "exit" else (record[0], "exit")

    held = {identity(record): record for record in goldens.RECORDS}
    made = {identity(record): record for record in reproduced}
    differences: "list[str]" = []
    skips: "list[str]" = []
    quoted: "set[str]" = set()
    if root is not None:
        battery = _battery()
        for case in battery.RECORDED:
            folder = root / (case.on or case.key)
            if cli._quoted_for_the_shell(f"{folder.resolve()}") != f"{folder.resolve()}":
                quoted.add(case.key)
    for key in sorted(set(held) | set(made), key=repr):
        record = held.get(key) or made.get(key)
        assert record is not None
        why = _skipped(record, goldens)
        if not why and record[1] in (OUT, ERR) and record[0] in quoted:
            why = "the case's folder would need quoting for a shell"
        if why:
            skips += [f"{key}: {why}"]
            continue
        if key not in held:
            differences += [f"{key}: made by this run, absent from the goldens: {made[key]}"]
        elif key not in made:
            differences += [f"{key}: in the goldens, not made by this run: {held[key]}"]
        elif held[key] != made[key]:
            differences += [f"{key}: the goldens hold {held[key]}, this run made {made[key]}"]
    return differences, skips


def consistency(goldens: typing.Any) -> "list[str]":
    """The stored digests that differ from the ones computed again (the seal's pattern)."""
    found: "list[str]" = []
    if records_digest(goldens.RECORDS) != goldens.RECORDS_DIGEST:
        found += ["RECORDS_DIGEST: the records were edited without recording again"]
    if battery_digest() != goldens.BATTERY_DIGEST:
        found += ["BATTERY_DIGEST: a recorded case changed without recording again"]
    if recorder_digest() != goldens.RECORDER_DIGEST:
        found += ["RECORDER_DIGEST: the recorder changed without recording again"]
    return found


_HEADER = '''"""The stage-5 goldens -- GENERATED by tools/goldens/record_stage5_goldens.py --write.

Do not edit by hand. Plan P4-D395 part 5 and `K-S5-02`: one line per
case and record (the exit status; each file of the case's folder by
SHA-256, bytes and lines, a link by the name it points at; each run of
the screen's transcript by stream, index, SHA-256, characters and
lines), the folder replaced by `<FOLDER>` and the version by
`<VERSION>`. The three digests are consistency checks, computed again
by `tests/test_stage5_gate.py`; what is authoritative is CI's guarded
reproduction (`.github/workflows/ci.yml`).
"""
'''


def render(records: "typing.Sequence[Record]") -> str:
    """The goldens module's text for these records."""
    lines = [
        _HEADER,
        f"RECORDER_PYTHON = {python_version()!r}",
        f"BATTERY_DIGEST = {battery_digest()!r}",
        f"RECORDER_DIGEST = {recorder_digest()!r}",
        "RECORDS = (",
    ]
    lines += [f"    {record!r}," for record in records]
    lines += [")", f"RECORDS_DIGEST = {records_digest(records)!r}", ""]
    return "\n".join(lines)


def _import_the_product() -> None:
    """Import every module of the package and the libraries a run loads."""
    import synthtwin

    package = pathlib.Path(synthtwin.__file__).resolve().parent
    for source in sorted(package.glob("*.py")):
        if source.stem in ("__init__", "__main__"):
            continue
        importlib.import_module(f"synthtwin.{source.stem}")
    for library in ("numpy", "pandas", "pyarrow", "pyarrow.csv"):
        importlib.import_module(library)


def negative_control(guard_runner: typing.Any) -> str:
    """Prove the hook refuses; return "" when it did, else what went wrong."""
    try:
        if "socket" in sys.modules:
            opened = sys.modules["socket"].socket()
            opened.close()
        else:
            importlib.import_module("socket")
    except RuntimeError as refused:
        if f"{refused}".startswith(guard_runner.GUARD_MESSAGE):
            return ""
        return f"the hook stopped socket with another message: {refused}"
    return "the hook did not stop socket: the guard is not installed"


def main(argv: "list[str] | None" = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--write", action="store_true", help="record the goldens again")
    options = parser.parse_args(argv)
    _import_the_product()
    sys.path.insert(0, f"{ROOT / 'tools' / 'provenance'}")
    guard_runner = importlib.import_module("guard_runner")
    battery = _battery()
    goldens: "typing.Any | None" = None
    if not options.write:
        goldens = importlib.import_module("stage5_goldens")
    guard_runner.install_guard()
    failed = negative_control(guard_runner)
    if failed:
        print(f"NEGATIVE CONTROL FAILED: {failed}. Nothing recorded.", file=sys.stderr)
        return 1
    with tempfile.TemporaryDirectory(prefix="stage5-") as made:
        root = pathlib.Path(made)
        records, _captures = reproduce(root)
        if options.write:
            TARGET.write_text(render(records), encoding="utf-8", newline="\n")
            print(f"recorded {len(records)} records of {len(battery.RECORDED)} cases into {TARGET}")
            return 0
        assert goldens is not None
        differences = consistency(goldens)
        moved, skips = compare(records, goldens, root)
        differences += moved
    for line in skips:
        print(f"skipped {line}")
    for line in differences:
        print(f"DIFFERS {line}", file=sys.stderr)
    print(f"{len(records)} records reproduced; {len(differences)} differ; {len(skips)} skipped")
    return 1 if differences else 0


if __name__ == "__main__":
    sys.exit(main())
