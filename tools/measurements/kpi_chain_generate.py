def _oracle():  # type: ignore[no-untyped-def]
    import importlib.util

    spec = importlib.util.spec_from_file_location("chb_chain_oracle", ROOT / "tools" / "reference" / "chain_oracle.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def association(rows: int, seed: int = 5) -> "tuple[list[str], list[list[str]]]":
    """K-S6-01's table (`tests/kpi_shapes.association_table`) at ``rows`` rows and table draw ``seed``."""
    draw = random.Random(seed)
    body: "list[list[str]]" = []
    for _ in range(rows):
        age = draw.gauss(55, 12)
        sbp = 100 + 0.8 * age + draw.gauss(0, 8)
        group = draw.choice("FM")
        died = "yes" if draw.random() < (0.6 if age > 65 else 0.1) else "no"
        body += [[f"{age:.0f}", f"{sbp:.0f}", group, died]]
    return ["age", "sbp", "group", "died"], body


def pregnancy_ward(rows: int) -> "tuple[list[str], list[list[str]]]":
    """A ward asking a pregnancy of women alone, so its families publish noughts; some records hold nothing."""
    draw = random.Random(20261025)
    body: "list[list[str]]" = []
    for place in range(rows):
        if draw.random() < 0.004:
            body += [[""] * 6]
            continue
        gender = draw.choice(["F", "M"])
        stay = 0 if draw.random() < 0.2 else min(int(draw.lognormvariate(1.3, 1.0)), 300)
        lab = "NA" if draw.random() < 0.03 else f"{draw.lognormvariate(1.5, 0.5):.2f}"
        pregnant = "" if gender == "M" else ("yes" if draw.random() < 0.08 + 0.002 * stay else "no")
        minutes = int(min(max(draw.gauss(14 * 60, 180), 0), 1439))
        body += [[f"R{place:07d}", str(stay), lab, gender, pregnant, f"{minutes // 60:02d}:{minutes % 60:02d}"]]
    return ["record", "stay", "lab", "gender", "pregnant", "arrival"], body


def _codes_back(path: pathlib.Path, described: "bt._Described") -> "dict[str, tuple[list[int], list[list[int]], list[int]]]":
    """Each eligible column's `L0` band on each tabled row of a written twin, its level maps and band counts."""
    back = reading.read_table(str(path), small_cell_floor=FLOOR)
    settings = taxonomy.Settings(small_cell_floor=FLOOR)
    blocks: "dict[str, tuple[int, dict[str, object]]]" = {}
    for place, block in enumerate(described.document["columns"]):  # type: ignore[arg-type]
        blocks[f"{block['name']}"] = (place, block)
    blank = chain_rules.records_holding_nothing(described.document)
    held = [reading.column_values(back, place) for place in range(len(back.column_names))]
    skipped: "set[int]" = set()
    for row in range(back.n_rows):
        if len(skipped) < blank and all(dialect.holds_nothing(column[row]) for column in held):
            skipped |= {row}
    held = []
    out: "dict[str, tuple[list[int], list[list[int]], list[int]]]" = {}
    assert described.statistical is not None
    for entry in described.statistical["ladder"]:  # type: ignore[union-attr]
        place, block = blocks[entry["column"]]
        read = chain.read_column(back, place, block, settings, SPELLED, "", blank)
        assert read is not None
        to_l0: "dict[object, int]" = {}
        for band, names in enumerate(entry["l0"]):
            for item in names:
                to_l0[tuple(item) if isinstance(item, list) else item] = band
        maps = [list(range(len(entry["l0"]))), [0] * len(entry["l0"]), [0] * len(entry["l0"])]
        for level, key in ((1, "l1"), (2, "l2")):
            for band, members in enumerate(entry[key]):
                for member in members:
                    maps[level][member] = band
        rows: "list[int]" = []
        for row in range(back.n_rows):
            if row in skipped:
                continue
            start = read.start.names[read.codes[row]] if read.codes[row] >= 0 else None
            rows += [to_l0[start] if start in to_l0 else -1]
        out[entry["column"]] = (rows, maps, [len(entry["l0"]), len(entry["l1"]), len(entry["l2"])])
    return out


def family_tables(path: pathlib.Path, described: "bt._Described") -> "list[list[list[int]]]":
    """Each family's table in a written twin at its published levels, one row a parent cell."""
    codes = _codes_back(path, described)
    out: "list[list[list[int]]]" = []
    assert described.statistical is not None
    for family in described.statistical["chain"]:  # type: ignore[union-attr]
        rows, maps, counts = codes[family["child"]]
        level = int(family["level"][1])
        parents = [(p["column"], int(p["level"][1])) for p in family["parents"]]
        cells = 1
        for name, parent_level in parents:
            cells *= codes[name][2][parent_level]
        table = [[0] * counts[level] for _ in range(cells)]
        for row in range(len(rows)):
            if rows[row] < 0 or any(codes[name][0][row] < 0 for name, _level in parents):
                raise SystemExit(f"a row of {family['child']} stands in no published band")
            cell = 0
            for name, parent_level in parents:
                parent_rows, parent_maps, parent_counts = codes[name]
                cell = cell * parent_counts[parent_level] + parent_maps[parent_level][parent_rows[row]]
            table[cell][maps[level][rows[row]]] += 1
        out += [table]
    return out


def _rates_and_odds(published: "list[list[int]]", found: "list[list[int]]") -> "tuple[int, int, int, int]":
    """Rates and odds ratios at the published levels, compared exactly (as tests/test_stage6_chain_generate.py does)."""
    rates = rates_off = odds = odds_off = 0
    for place in range(len(published)):
        total = sum(published[place])
        found_total = sum(found[place])
        for band in range(len(published[place])):
            if total:
                rates += 1
                if found_total == 0 or published[place][band] * found_total != found[place][band] * total:
                    rates_off += 1
    width = len(published[0]) if published else 0
    for first in range(len(published)):
        for second in range(first + 1, len(published)):
            for low in range(width):
                for high in range(low + 1, width):
                    if 0 in (published[first][low], published[first][high], published[second][low], published[second][high]):
                        continue
                    odds += 1
                    left = published[first][low] * published[second][high] * found[first][high] * found[second][low]
                    right = published[first][high] * published[second][low] * found[first][low] * found[second][high]
                    if left != right:
                        odds_off += 1
    return rates, rates_off, odds, odds_off


def _tiers_of(published: "list[list[int]]", table: "list[list[int]]") -> "tuple[int, int]":
    """A table's units in the published table's noughts and its summed distance to it (G16.6's first two tiers)."""
    units = sum(table[i][j] for i in range(len(table)) for j in range(len(table[i])) if published[i][j] == 0)
    distance = sum(abs(table[i][j] - published[i][j]) for i in range(len(table)) for j in range(len(table[i])))
    return units, distance


def moved_tiers(published: "list[list[int]]", rows: "list[int]", columns: "list[int]") -> "tuple[int, int]":
    """G16.6's first two tiers solved INDEPENDENTLY of the product's flow: over the whole-number tables with
    row totals ``rows`` and column totals ``columns``, the fewest units in the published table's noughts,
    then, holding that, the least summed distance to the published table. Two integer programs over the
    transportation polytope, solved exactly by scipy's HiGHS (`scipy.optimize.milp`)."""
    import numpy
    from scipy.optimize import Bounds, LinearConstraint, milp

    depth, width = len(rows), len(columns)
    cells = depth * width
    flat = [published[i][j] for i in range(depth) for j in range(width)]
    margins = numpy.zeros((depth + width, cells))
    for i in range(depth):
        for j in range(width):
            margins[i, i * width + j] = 1
            margins[depth + j, i * width + j] = 1
    totals = numpy.array(list(rows) + list(columns), dtype=float)
    noughts = numpy.array([1.0 if value == 0 else 0.0 for value in flat])
    first = milp(noughts, constraints=[LinearConstraint(margins, totals, totals)], integrality=numpy.ones(cells),
                 bounds=Bounds(0, numpy.inf))
    if not first.success:
        raise SystemExit("the moved table's first tier has no solution")
    units = int(round(first.fun))
    # x then d: d >= x - p and d >= p - x, the noughts' units fixed at the first tier's minimum.
    whole = numpy.zeros((depth + width + 1 + 2 * cells, 2 * cells))
    low = numpy.zeros(depth + width + 1 + 2 * cells)
    high = numpy.zeros(depth + width + 1 + 2 * cells)
    whole[:depth + width, :cells] = margins
    low[:depth + width] = totals
    high[:depth + width] = totals
    whole[depth + width, :cells] = noughts
    low[depth + width] = units
    high[depth + width] = units
    for at in range(cells):
        line = depth + width + 1 + 2 * at
        whole[line, at] = 1
        whole[line, cells + at] = -1
        low[line] = -numpy.inf
        high[line] = flat[at]
        whole[line + 1, at] = -1
        whole[line + 1, cells + at] = -1
        low[line + 1] = -numpy.inf
        high[line + 1] = -flat[at]
    cost = numpy.concatenate([numpy.zeros(cells), numpy.ones(cells)])
    second = milp(cost, constraints=[LinearConstraint(whole, low, high)], integrality=numpy.ones(2 * cells),
                  bounds=Bounds(0, numpy.inf))
    if not second.success:
        raise SystemExit("the moved table's second tier has no solution")
    return units, int(round(second.fun))


def _tables(rows_list: "list[int]", folder: pathlib.Path, zoo: bool, draws: "list[int]") -> "list[tuple[str, pathlib.Path, list[int]]]":
    out: "list[tuple[str, pathlib.Path, list[int]]]" = []

    def written(name: str, made: "tuple[list[str], list[list[str]]]") -> pathlib.Path:
        path = folder / f"{name}.csv"
        path.write_text(fixtures.rows_to_csv(made[0], made[1]), encoding="utf-8", newline="\n")
        return path

    for rows in rows_list:
        out += [(f"association{rows}", written(f"association{rows}", association(rows)), [0, 1, 2, 3, 4])]
        out += [(f"pregnancy{rows}", written(f"pregnancy{rows}", pregnancy_ward(rows)), [])]
    out += bt._tables(rows_list, folder, zoo, [], draws)
    return out


def measure(rows_list: "list[int]", seeds: "list[int]", zoo: bool, draws: "list[int]") -> "dict[str, object]":
    started = time.time()
    co = _oracle()
    value: "dict[str, object]" = {
        "twins": 0, "families_checked": 0, "exact_families": 0, "cells_checked": 0, "cells_off": 0,
        "rates_checked": 0, "rates_off": 0, "odds_ratios_checked": 0, "odds_ratios_off": 0,
        "noughts_checked": 0, "rows_in_noughts": 0, "moved_families": 0, "moved_checked": 0,
        "moved_off": 0, "moved_exact_checked": 0, "words_off": 0, "stray_rows_named": 0,
    }
    moved_named: "list[str]" = []
    off_named: "list[str]" = []
    with tempfile.TemporaryDirectory(prefix="synthtwin-chain-generate-") as kept:
        folder = pathlib.Path(kept)
        for name, path, own in _tables(rows_list, folder, zoo, draws):
            described = bt._described(folder, name.replace("/", "-"), path)
            if described.loaded is None or described.statistical is None:
                path.unlink(missing_ok=True)
                continue
            planned = generation.plan_generation(described.loaded).words_planned
            for seed in (own or seeds):
                twin = generation.generate_held(described.loaded, seed)
                value["twins"] = int(value["twins"]) + 1  # type: ignore[call-overload]
                if twin.words_drawn != planned:
                    value["words_off"] = int(value["words_off"]) + 1  # type: ignore[call-overload]
                moved = {note.column for note in twin.deviations if note.fact == "chain"}
                value["stray_rows_named"] = int(value["stray_rows_named"]) + sum(1 for note in twin.deviations if note.fact == "empty_rows")  # type: ignore[call-overload]
                out = bt._twin_file(folder, described, described.loaded, twin, f"{seed}-chain")
                tables = family_tables(out, described)
                out.unlink()
                for family, table in zip(described.statistical["chain"], tables):  # type: ignore[union-attr]
                    value["families_checked"] = int(value["families_checked"]) + 1  # type: ignore[call-overload]
                    published = family["table"]
                    if family["child"] in moved:
                        value["moved_families"] = int(value["moved_families"]) + 1  # type: ignore[call-overload]
                        moved_named += [f"{name}@{seed}: {family['child']}"]
                        rows = [sum(row) for row in table]
                        columns = [sum(table[place][band] for place in range(len(table))) for band in range(len(table[0]))]
                        value["moved_checked"] = int(value["moved_checked"]) + 1  # type: ignore[call-overload]
                        if moved_tiers(published, rows, columns) != _tiers_of(published, table):
                            value["moved_off"] = int(value["moved_off"]) + 1  # type: ignore[call-overload]
                            off_named += [f"{name}@{seed}: {family['child']} moved"]
                        if len(table) * len(table[0]) <= MOVED_CELLS and sum(rows) <= MOVED_ROWS:
                            expected, _named = co.moved_target(published, rows, columns)
                            value["moved_exact_checked"] = int(value["moved_exact_checked"]) + 1  # type: ignore[call-overload]
                            if expected != table:
                                value["moved_off"] = int(value["moved_off"]) + 1  # type: ignore[call-overload]
                                off_named += [f"{name}@{seed}: {family['child']} moved, the oracle's table"]
                        continue
                    value["exact_families"] = int(value["exact_families"]) + 1  # type: ignore[call-overload]
                    for place in range(len(published)):
                        for band in range(len(published[place])):
                            value["cells_checked"] = int(value["cells_checked"]) + 1  # type: ignore[call-overload]
                            if table[place][band] != published[place][band]:
                                value["cells_off"] = int(value["cells_off"]) + 1  # type: ignore[call-overload]
                            if published[place][band] == 0:
                                value["noughts_checked"] = int(value["noughts_checked"]) + 1  # type: ignore[call-overload]
                                value["rows_in_noughts"] = int(value["rows_in_noughts"]) + table[place][band]  # type: ignore[call-overload]
                    rates, rates_off, odds, odds_off = _rates_and_odds(published, table)
                    for key, count in (("rates_checked", rates), ("rates_off", rates_off), ("odds_ratios_checked", odds), ("odds_ratios_off", odds_off)):
                        value[key] = int(value[key]) + count  # type: ignore[call-overload]
                    if table != published:
                        off_named += [f"{name}@{seed}: {family['child']}"]
            path.unlink(missing_ok=True)
    value["moved_named"] = sorted(set(entry.split(": ")[0].split("@")[0] + ": " + entry.split(": ")[1] for entry in moved_named))
    value["off_named"] = off_named
    value["chain_refused"] = sorted(f"{name}: {why}" for name, why in bt.REFUSED.items())
    value["seconds"] = round(time.time() - started, 1)
    return value


def whole_rows(rows: int, seeds: "list[int]") -> "dict[str, object]":
    """K-S6-05 on K-S6-01's table: whole real rows in the chain's twin, today's twin and a fresh real sample."""
    started = time.time()
    with tempfile.TemporaryDirectory(prefix="synthtwin-whole-rows-") as kept:
        folder = pathlib.Path(kept)
        header, body = association(rows)
        path = folder / "association.csv"
        path.write_text(fixtures.rows_to_csv(header, body), encoding="utf-8", newline="\n")
        described = bt._described(folder, "association", path)
        assert described.loaded is not None
        held: "dict[tuple[str, ...], int]" = {}
        for row in body:
            held[tuple(row)] = held[tuple(row)] + 1 if tuple(row) in held else 1
        real = set(held)
        unique = {row for row in held if held[row] == 1}
        found: "dict[str, list[int]]" = {"chain": [], "product": [], "fresh": []}
        distinct: "dict[str, list[int]]" = {"chain": [], "product": [], "fresh": []}
        on_unique: "dict[str, list[int]]" = {"chain": [], "product": [], "fresh": []}
        for seed in seeds:
            made: "dict[str, list[tuple[str, ...]]]" = {}
            for key, profile_ in (("chain", described.loaded), ("product", described.plain)):
                text = "".join(rendering.twin_csv_pieces(generation.generate_held(profile_, seed)))
                made[key] = [tuple(line.split(",")) for line in text.strip("\n").split("\n")[1:]]
            made["fresh"] = [tuple(row) for row in association(rows, 1000 + seed)[1]]
            for key in ("chain", "product", "fresh"):
                found[key] += [sum(1 for row in made[key] if row in real)]
                on_unique[key] += [sum(1 for row in made[key] if row in unique)]
                distinct[key] += [len({row for row in made[key] if row in unique})]
            made = {}
    out: "dict[str, object]" = {"rows": rows, "seeds": len(seeds), "real_unique_rows": len(unique)}
    for key in ("chain", "product", "fresh"):
        out[f"{key}_whole_rows_mean"] = round(sum(found[key]) / len(found[key]), 2)
        out[f"{key}_whole_rows_max"] = max(found[key])
        out[f"{key}_distinct_unique_real_mean"] = round(sum(distinct[key]) / len(distinct[key]), 2)
        out[f"{key}_rows_on_unique_real_mean"] = round(sum(on_unique[key]) / len(on_unique[key]), 2)
    out["distinct_unique_minus_fresh_mean"] = round(
        float(out["chain_distinct_unique_real_mean"]) - float(out["fresh_distinct_unique_real_mean"]), 2  # type: ignore[arg-type]
    )
    # PLAN-DEC 4.1's "not worse", as lane CHb's inputs read it: no more
    # whole real rows than a fresh real sample of the same size holds.
    out["chain_minus_fresh_mean"] = round(float(out["chain_whole_rows_mean"]) - float(out["fresh_whole_rows_mean"]), 2)  # type: ignore[arg-type]
    out["seconds"] = round(time.time() - started, 1)
    return out


def _argument(flag: str, default: "list[int]") -> "list[int]":
    if flag in sys.argv:
        return [int(item) for item in sys.argv[sys.argv.index(flag) + 1].split(",")]
    return default


def main() -> int:
    k_s6_03 = measure(_argument("--rows", [20000]), _argument("--seeds", [0, 1, 2]), "--no-zoo" not in sys.argv, _argument("--draws", [7, 11]))
    k_s6_05 = whole_rows(_argument("--whole-rows", [20000])[0], _argument("--whole-seeds", list(range(20))))
    if "--kpi" in sys.argv:
        print("KPI " + json.dumps({"id": "K-S6-03", "value": k_s6_03, "detail": "the chain's generator (lane CHb)"}, sort_keys=True))
        print("KPI " + json.dumps({"id": "K-S6-05", "value": k_s6_05, "detail": "whole real rows (lane CHb)"}, sort_keys=True))
    else:
        print(json.dumps({"K-S6-03": k_s6_03, "K-S6-05": k_s6_05}, indent=1, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
