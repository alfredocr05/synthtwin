"""K-S6-03 and K-S6-05: the chain's generator, layer L1, on the product's own twins (lane CHb, plan P4-D435).

Every table is invented (no real data), described with the chain's switch
(`chain.describe`, a fixed test key), loaded behind it
(`contract.load_profile(..., chain=True)`) and generated by the product
(`generation.generate_held`, method G16); each twin is written, read back
the way the profile reads a table (`chain.read_column`, the first `E`
records holding nothing no tabled row), and every family's table counted
at its published levels.

- K-S6-03, RATES AND ODDS RATIOS AT EVERY FAMILY'S PUBLISHED LEVELS,
  EXACT: each family whose TARGET is its published table (method G16.0:
  the twin's parent cells and the child's band totals hold its margins)
  holds that table cell for cell: `cells_off` 0 over `cells_checked`
  cells of `exact_families` families; so every rate (a cell over its
  parent cell's rows) and every odds ratio of two bands in two parent
  cells is the real table's: `rates_off` 0 over `rates_checked`,
  `odds_ratios_off` 0 over `odds_ratios_checked`; no row stands in a
  published nought: `rows_in_noughts` 0 over `noughts_checked`. A family
  dealt against its MOVED TABLE (G16.6: a column made without its band
  totals, or parent cells a move upstream changed) is named in
  `moved_named`, and EVERY one is judged at the product's own size
  (lane CHb's first repair, its statistics skeptic's item 2) against an
  INDEPENDENT SOLVE of G16.6's first two tiers over the read-back table's
  own row and column totals: the fewest units in published noughts, then
  the least summed distance to the published table, each an integer
  program over the transportation polytope (scipy's HiGHS, `milp`); the
  twin's units in noughts and its summed distance must equal the two
  minima, so where the second is nought the table IS the published one:
  `moved_off` 0 over `moved_checked`; where the oracle's search also ends
  (`MOVED_CELLS` cells and `MOVED_ROWS` rows at most) the whole table is
  held to the oracle's moved table (`tools/reference/chain_oracle.py`,
  `moved_target`) too, `moved_exact_checked`. Every twin draws the
  words its plan states: `words_off` 0. Reported: the tables whose
  switched description its own loader refused (`chain_refused`).
- K-S6-05, WHOLE REAL ROWS: on K-S6-01's table (`association`, the
  recipe of `tests/kpi_shapes.association_table` at `--whole-rows`
  rows), the twin rows equal in every column to a real row, for the
  chain's twin, for the twin of the same description without the chain
  (today's twin) and for a FRESH REAL SAMPLE of the same size (the same
  recipe at another draw), each the mean and the largest over the seeds,
  and the chain's mean less the fresh sample's (`chain_minus_fresh_mean`,
  at most 0: no more whole real rows than a fresh real sample holds).
  THE RARE ROWS (lane CHb's first repair, its statistics skeptic's item
  4): the real rows held by ONE real row are counted apart, by the
  DISTINCT such rows each twin reproduces (`*_distinct_unique_real_mean`,
  the chain's less the fresh sample's at most 0,
  `distinct_unique_minus_fresh_mean`) and, reported beside it, by the
  twin rows equal to one (`*_rows_on_unique_real_mean`), so a total
  driven by common rows hides no rise on rare ones.

    PYTHONPATH=src:tests python tools/measurements/kpi_chain_generate.py --kpi [--rows 20000] [--seeds 0,1,2] [--draws 7,11] [--no-zoo] [--whole-rows 20000] [--whole-seeds 0..19]

The battery: K-S6-01's table at 20,000 rows (seeds 0 to 4), lane BT's
battery (`kpi_band_totals`: the ten-column table at table draws 7 and
11, the count of few values, a ward holding records that hold nothing as
a text file and as a workbook, the every-role table) at seeds 0 to 2, a
ward asking a pregnancy of women alone (published noughts) and the
health zoo's 25 exports at 20,000 rows at seeds 0 and 1, unless
`--no-zoo`. One process of about 200 MB, about 40 minutes. The
200,000-row leg is a separate run under the heavy-slot guard
(`--rows 200000 --seeds 0,1,2 --draws 7 --no-zoo --whole-rows 200000
--whole-seeds 0,1,2,3,4`).
"""

