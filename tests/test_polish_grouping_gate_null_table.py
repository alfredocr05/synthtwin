"""G16.3's GROUPING GATE on the null table through the commands a person types (lane CHG, plan P4-D492; LANE CHG
RULINGS 1 (8)): THE ONE SLOW LINE.

In a file of its own beside tests/test_polish_grouping_gate.py since the lane's repair 1, so that each file stays
under the suite's three CPU minutes: lane MU's current route S (tests/twin_routes.py, lane MU's file at its READY
head `8275a8c5`, brought unchanged at batch 4u's merge; the lane's repair 1 read its copy at `e18f288b`, whose run
folder CHON's repair 1 refuses) answers each column's questions with what the person who holds the table knows of it,
the checklist among them, and walks more `synthtwin profile` rounds than the copy the build read, so the gate file
with this line in it read 183.6 CPU seconds (at a one-minute load of 94). Since the lane's repair 3 (the suite
repair) the plan held is the one `synthtwin generate` laid out for the twin it wrote, as the command laid it out: the
module hands no description to the loader itself (the floor of tests/test_description_line_endings.py reads every
module that does), and the plan it holds is the plan the twin was polished with. WHAT IS HELD, red on lane CHON's head
`875b1b93` (its twin calls 22.9 per cent of the pairs associated and aims at all 160 grouping moments) and on the
gate's mutants (the gate off; a dropped target kept at nought; the correlations gated too): the null table ST5
(15 independent columns, tests/analyst_tables.py) at 20,000 rows, table seed 1, described and generated by the
commands a person types, its questions answered with what the person knows of each column: the polish aims at its
42 correlations and none of its 160 grouping moments; at most 15 per cent of its 105 pairs called associated by the
analyst's 5 per cent test (`K-BC-03`'s bar for every reading) and at most 8 invented; the twin's group means by the
12-level label at a fresh draw's distance.
"""

import copy
import pathlib

import pytest
import test_polish_grouping_gate as gate

from synthtwin import contract, generation


def test_the_null_table_through_the_commands_a_person_types_at_20000_rows(tmp_path: pathlib.Path,
                                                                          monkeypatch: pytest.MonkeyPatch) -> None:
    """ST5, fifteen columns drawn independently (tests/analyst_tables.py), at 20,000 rows, table seed 1, described by
    `synthtwin profile` with its questions answered as the person who holds it answers them and generated by
    `synthtwin generate --seed 0` (lane MU's route S, tests/twin_routes.py). The polish aims at the 42 correlations of
    its seven numbers and at none of the 160 grouping moments its description publishes (the head aims at all 160);
    the analyst's 5 per cent test (`analyst_battery.st5_pair_p`) calls at most 15 per cent of the 105 pairs associated
    (`K-BC-03`'s bar for every reading; the head 22.9 per cent, 24 pairs) and invents at most 8 (a pair the twin calls
    associated and the real table does not; the head 20, the gated twin 5); and the twin's means of each of the eleven
    other columns in the 12-level label's groups copy the real table's chance pattern less than half way (mean copy
    ratio under 0.5; the head 0.83) at a fresh draw's distance (mean group chi-square under 13 on 11 degrees of freedom;
    the head 21.5). The plan is the one `synthtwin generate --seed 0` laid out in this run (G16.3's `_polish_layout`,
    called once a run, its plan copied as it was laid out), and the head's plan is laid out from the description as
    that command loaded it, with the gate off. `K-BC-03`'s median over nine readings stands in its driver."""
    import analyst_battery
    import analyst_tables
    import twin_routes

    text = analyst_tables.text("ST5", 20000, 1)
    # Every blank entry answered from what the person knows of each column (lane MU's route S answers the
    # checklist too; left blank, `ward` and the checklist stay open and no chain is drawn).
    described = twin_routes.describe_typed(tmp_path, "ST5", text, knows=analyst_tables.KNOWS["ST5"])
    # The command's own plan: each call of G16.3's layout during `synthtwin generate`, with the description it was
    # handed, recorded as it is laid out (the rounds then move each target's aim in place) and passed on unchanged
    # (the twin is the one the command writes).
    made: "list[tuple[contract.Profile, list[tuple[str, list[generation._PolishTarget]]]]]" = []
    lay_out = generation._polish_layout

    def laid_out(profile: contract.Profile) -> "generation._PolishLayout":
        layout = lay_out(profile)
        made.append((profile, copy.deepcopy(layout.plan)))
        return layout

    with monkeypatch.context() as local:
        local.setattr(generation, "_polish_layout", laid_out)
        twin_text, _report = twin_routes.generate(described, 0)
    assert len(made) == 1, len(made)
    loaded, plan = made[0]
    with monkeypatch.context() as local:
        local.setattr(generation, "_POLISH_GATE", False)
        head = generation._polish_layout(loaded).plan
    assert sum(1 for _name, targets in head for t in targets if t.kind != "pair") == 160
    assert [(name, t) for name, targets in plan for t in targets] == [
        (name, t) for name, targets in head for t in targets if t.kind == "pair"]
    assert sum(1 for _name, targets in plan for _t in targets) == 42
    real = analyst_battery.read(text, "real")
    twin = analyst_battery.read(twin_text, "twin")
    names = analyst_tables.ST5_COLUMNS
    pairs = [(a, b) for at, a in enumerate(names) for b in names[at + 1:]]
    called = [analyst_battery.st5_pair_p(twin, a, b) < 0.05 for a, b in pairs]
    invented = [c and not analyst_battery.st5_pair_p(real, a, b) < 0.05 for c, (a, b) in zip(called, pairs)]
    assert len(pairs) == 105 and sum(called) / len(pairs) <= 0.15 and sum(invented) <= 8, (sum(called), sum(invented))
    others = [name for name in names if name not in analyst_battery.ST5_LABELS]
    measured = [gate._copy_and_chi_square(text, twin_text, "ward", value) for value in others]
    assert sum(ratio for ratio, _square in measured) / len(measured) < 0.5, measured
    assert sum(square for _ratio, square in measured) / len(measured) < 13.0, measured
