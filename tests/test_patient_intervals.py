def _late_implied(found: "patient_intervals.Found", hazard: dict, switch_edges: "list[fractions.Fraction]") -> "list[int]":
    """Read from the patients: for each switch edge and each published time edge at or below it (or one unit above it), the patients ending at or after the time edge less those switching at or after the switch edge; and, where the switch margin publishes ends after the switch of one value alone, the same of the patients ending with it."""
    margin = hazard["switch"]["events"] if hazard["switch"] is not None else None
    alone = [at for at in range(len(margin)) if margin[at][1] > 0] if margin is not None else []
    values = list(found.end[2]) if found.end else []
    out: "list[int]" = []
    for switch_edge in switch_edges:
        turned = sum(1 for time in found.switched if time is not None and time >= switch_edge)
        for time_edge in [fractions.Fraction(one) for one in hazard["edges"]]:
            if time_edge <= switch_edge + 1:
                out += [sum(1 for end in found.follow if end >= time_edge) - turned]
                if len(alone) == 1:
                    out += [sum(1 for at, end in enumerate(found.follow) if end >= time_edge and found.ended[at] == values[alone[0]]) - turned]
    return out


