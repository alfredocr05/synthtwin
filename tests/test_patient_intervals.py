    rows_of: "list[list[int]]" = []
    for _patient in range(patients):
        rows = draw.randint(2, 4)
        bounds = [0] + sorted(draw.sample(range(1, 90), rows - 1)) + [90 + draw.randint(1, 30)]
        turn = draw.randint(1, rows - 1) if draw.random() < 0.6 else rows
