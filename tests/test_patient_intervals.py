def _role_columns(draw: random.Random, patients: int) -> "tuple[list[patient_intervals.RowColumn], list[list[int]]]":
    """Invented rows: the intervals, an end coded 0 to 2, a treatment switching once, and two binary decoys (one switching once on some patients, one at 0 but on some patients' last row)."""
