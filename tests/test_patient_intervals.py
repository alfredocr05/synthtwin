def _every_count(grain: dict) -> "list[int]":
    out: "list[int]" = []
    for entry in grain["switches"]:
        out += list(entry["patients"]) + [entry["never"]]
        if "origin" in entry:
            # The patients treated from the origin, and the first band's and every other switch (implied directly).
            one, more = entry["origin"]
            out += [one, more, entry["patients"][0] - one - more, sum(entry["patients"]) - one - more]
    hazard = grain["hazard"]
    for line in hazard["events"]:
        out += list(line)
    margin = hazard["switch"]["events"] if hazard["switch"] is not None else None
    for line in margin or []:
        out += list(line)
    for column in hazard["columns"]:
        for line in column["events"]:
            out += list(line)
        if "switches" in column:
            # Each band's switches, and the patients of the band who never switch (implied directly); where the
            # margin's zeros fix them, each band's ends of the values a state's margin holds less that state's patients.
            people = [sum(line[band] for line in column["events"]) for band in range(len(column["switches"]))]
            states = [[people[band] - column["switches"][band] for band in range(len(people))], list(column["switches"])]
            out += states[1] + states[0]
            for state in range(2):
                held = [value for value in range(len(column["events"])) if margin is None or margin[value][state] > 0]
                out += [sum(column["events"][value][band] for value in held) - states[state][band] for band in range(len(people))]
    return out


