def _start_grade3(rows_of: "list[list[int]]", columns: "dict[str, list[str]]") -> float:
    """The grade III term of a Cox model of the time to the treatment's start (grade II and III, the age a decade over 60; the patients never treated censored at their end), by Newton's method on Breslow's partial likelihood, machine-free."""
    import math

    times: "list[tuple[float, int, list[float]]]" = []
    for rows in rows_of:
        grade, age = columns["grade"][rows[0]], float(columns["age"][rows[0]])
        started = [float(columns["start_day"][row]) for row in rows if columns["on_treatment"][row] == "1"]
        end = max(float(columns["stop_day"][row]) for row in rows)
        times += [(min(started) if started else end, 1 if started else 0, [float(grade == "II"), float(grade == "III"), (age - 60.0) / 10.0])]
    times.sort(key=lambda one: -one[0])
    beta = [0.0, 0.0, 0.0]
    for _step in range(25):
        gradient = [0.0] * 3
        information = [[0.0] * 3 for _row in range(3)]
        s0, s1, s2 = 0.0, [0.0] * 3, [[0.0] * 3 for _row in range(3)]
        at = 0
        while at < len(times):
            moment = times[at][0]
            tied = []
            while at < len(times) and times[at][0] == moment:
                weight = math.exp(sum(b * x for b, x in zip(beta, times[at][2])))
                s0 += weight
                for i in range(3):
                    s1[i] += weight * times[at][2][i]
                    for j in range(3):
                        s2[i][j] += weight * times[at][2][i] * times[at][2][j]
                tied += [times[at]]
                at += 1
            for _time, event, x in tied:
                if event:
                    for i in range(3):
                        gradient[i] += x[i] - s1[i] / s0
                        for j in range(3):
                            information[i][j] += s2[i][j] / s0 - s1[i] * s1[j] / s0 ** 2
        # Solve information . step = gradient (Gaussian elimination, three unknowns).
        matrix = [information[i] + [gradient[i]] for i in range(3)]
        for col in range(3):
            pivot = max(range(col, 3), key=lambda row: abs(matrix[row][col]))
            matrix[col], matrix[pivot] = matrix[pivot], matrix[col]
            for row in range(3):
                if row != col:
                    factor = matrix[row][col] / matrix[col][col]
                    matrix[row] = [a - factor * b for a, b in zip(matrix[row], matrix[col])]
        step = [matrix[i][3] / matrix[i][i] for i in range(3)]
        beta = [b + d for b, d in zip(beta, step)]
        if max(abs(d) for d in step) < 1e-9:
            break
    return beta[1]


