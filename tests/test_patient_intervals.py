def _column(name: str, texts: "list[str]") -> patient_intervals.RowColumn:
    readings: "list[fractions.Fraction | None]" = []
    for text in texts:
        try:
            readings += [fractions.Fraction(text)]
        except ValueError:
            readings += [None]
    role = "count" if all(one is not None for one in readings) else "categorical"
    return patient_intervals.row_column(name, patient_rules.CLASS_REPEATED, role, texts, readings)


def _small_table(draw: random.Random, patients: int) -> "list[list[tuple[int, int, str, str]]]":
    """Patients of 1 to 5 contiguous intervals from 0, a switch from 0 to 1 at one of their cuts, an end on the last row."""
    out: "list[list[tuple[int, int, str, str]]]" = []
    for _patient in range(patients):
        rows = draw.randint(1, 5)
        cuts = sorted(draw.sample(range(1, 60), rows - 1))
        end = cuts[-1] + draw.randint(1, 20) if cuts else draw.randint(1, 60)
        bounds = [0] + cuts + [end]
        switch_at = draw.randint(0, rows) if draw.random() < 0.6 else rows
        value = draw.choice(["0", "1", "2"])
        mine = []
        for at in range(rows):
            mine += [(bounds[at], bounds[at + 1], "1" if at >= switch_at else "0", value if at == rows - 1 else "0")]
        out += [mine]
    return out


BREAKS = ("none", "gap", "overlap", "late_origin", "switch_back", "end_early")


def _broken_copy(draw: random.Random, table: "list[list[tuple[int, int, str, str]]]", kind: str) -> "tuple[list[list[tuple[int, int, str, str]]], bool]":
    """The table with ONE patient broken in the way named, and whether a patient could be broken so."""
    out = [list(rows) for rows in table]
    places = list(range(len(out)))
    draw.shuffle(places)
    for place in places:
        rows = out[place]
        if kind == "none":
            return out, True
        if kind == "gap" and len(rows) >= 2 and rows[1][1] > rows[1][0] + 1:
            rows[1] = (rows[1][0] + 1,) + rows[1][1:]
            return out, True
        if kind == "overlap":
            rows[-1] = (rows[-1][0], rows[-1][0]) + rows[-1][2:]
            return out, True
        if kind == "late_origin" and rows[0][1] > 1:
            rows[0] = (1,) + rows[0][1:]
            return out, True
        if kind == "switch_back" and len(rows) >= 3 and rows[1][2] == "1":
            rows[2] = rows[2][:2] + ("0",) + rows[2][3:]
            return out, True
        if kind == "end_early" and len(rows) >= 2:
            rows[0] = rows[0][:3] + ("1",)
            return out, True
    return out, False


def _found(table: "list[list[tuple[int, int, str, str]]]", floor: int) -> "patient_intervals.Found | None":
    texts: "list[list[str]]" = [[], [], [], []]
    patients: "list[list[int]]" = []
    for rows in table:
        mine = []
        for row in rows:
            mine += [len(texts[0])]
            for at in range(4):
                texts[at] += [f"{row[at]}"]
        patients += [mine]
    columns = [_column(name, texts[at]) for at, name in enumerate(("start_day", "stop_day", "on_treatment", "outcome"))]
    return patient_intervals.found_on(columns, patients, floor)


def test_the_rules_stand_where_every_patient_keeps_them():
    """The three rules found on a table every patient keeps; each patient's follow-up, switch time and end value read."""
    table = [
        [(0, 10, "0", "0"), (10, 25, "1", "0"), (25, 40, "1", "1")],
        [(0, 7, "0", "2")],
        [(0, 5, "0", "0"), (5, 9, "0", "0")],
        [(0, 3, "1", "0"), (3, 8, "1", "1")],
    ]
    found = _found(table, 1)
    assert found is not None
    assert (found.start, found.stop, found.places) == ("start_day", "stop_day", 0)
    assert found.switch == ("on_treatment", "0", "1")
    assert found.end == ("outcome", "0", ("0", "1", "2"))
    assert found.follow == [40, 7, 9, 8]
    assert found.switched == [10, None, None, 0]
    assert found.ended == ["1", "2", "0", "1"]


def test_one_patient_breaking_a_rule_withholds_that_rule_over_a_generated_sweep():
    """Over 4,200 generated small tables: a rule is published exactly when every patient keeps it (ruling D8).

    Mutants: `_keeps_intervals` reading the first patient only, `_switch_of`
    allowing a change back, `_end_of` reading the last row only: each
    reads hundreds of these tables otherwise.
    """
    draw = random.Random(491)
    misread: "list[tuple[int, str]]" = []
    tried = {kind: 0 for kind in BREAKS}
    for case in range(4200):
        kind = BREAKS[case % len(BREAKS)]
        table = _small_table(draw, draw.randint(2, 9))
        table[0] = [(0, 4, "0", "0"), (4, 9, "1", "1")]
        table[1] = [(0, 6, "0", "0"), (6, 11, "0", "2")]
        broken, applied = _broken_copy(draw, table, kind)
        if not applied:
            continue
        tried[kind] += 1
        found = _found(broken, 1)
        if kind in ("gap", "overlap", "late_origin"):
            if found is not None:
                misread += [(case, kind)]
            continue
        if found is None:
            misread += [(case, kind)]
            continue
        # The roles are assigned jointly (repair 2): a column whose rule one patient breaks never takes that role;
        # where the outcome breaks the end rule, the treatment may stand as the end where it keeps that rule.
        switch_name = found.switch[0] if found.switch else None
        end_name = found.end[0] if found.end else None
        if kind == "none" and (switch_name, end_name) != ("on_treatment", "outcome"):
            misread += [(case, kind)]
        if kind == "switch_back" and (switch_name == "on_treatment" or end_name != "outcome"):
            misread += [(case, kind)]
        if kind == "end_early" and end_name == "outcome":
            misread += [(case, kind)]
    assert misread == []
    assert all(count >= 150 for count in tried.values()), tried


def test_a_rule_whose_spellings_fewer_patients_than_the_floor_hold_is_withheld():
    """An end value or a switch's spelling held by 1 to f - 1 patients publishes no rule (HIPAA: no value of so few)."""
