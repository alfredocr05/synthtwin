def _patients(names: "list[str]", columns: "list[list[str]]", person: str = "pid") -> "list[list[int]]":
    keys = columns[names.index(person)]
    rows_of: "dict[str, list[int]]" = {}
    for row, key in enumerate(keys):
        if key.strip():
            rows_of.setdefault(key, []).append(row)
    return list(rows_of.values())


def _broken(names: "list[str]", columns: "list[list[str]]") -> "tuple[int, int, int]":
    """Twin patients breaking the interval, switch and end-event rules, read in start order."""
    start = [fractions.Fraction(text) if text.strip() else None for text in columns[names.index("start_day")]]
    stop = [fractions.Fraction(text) if text.strip() else None for text in columns[names.index("stop_day")]]
    return patient_intervals.broken_by(
        _patients(names, columns), list(start), list(stop), columns[names.index("on_treatment")], ("0", "1"),
        columns[names.index("outcome")], "0",
    )


