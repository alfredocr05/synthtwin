def _floyd(follow: int, switched: "int | None", rho: int, shares: "list[float]") -> "list[int]":
    """Floyd's sample written again here, apart from the writer: the cuts of a patient from its shares."""
    fixed = [switched] if switched is not None and switched > 0 else []
    points = [point for point in range(1, follow) if point not in fixed]
    taken: "list[int]" = []
    wanted = rho - 1 - len(fixed)
    for at, top in enumerate(range(len(points) - wanted + 1, len(points) + 1)):
        pick = 1 + min(top - 1, int(shares[at] * top))
        taken += [top if pick in taken else pick]
    return sorted(fixed + [points[one - 1] for one in taken])


