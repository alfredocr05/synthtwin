def _histories(found: "patient_intervals.Found") -> "list[list[tuple[int, int, str, str]]]":
    """Each patient's rows `(a, b, switch, end)` as the rules read them: its follow-up cut where it switches and evenly over its rows."""
    out: "list[list[tuple[int, int, str, str]]]" = []
    for at in range(len(found.follow)):
        rows = max(1, len(found.order[at]))
        end = int(found.follow[at])
        time = found.switched[at]
        cuts = sorted({int(time)} if time is not None and 0 < time < end else set())
        step = 0
        while len(cuts) < rows - 1 and step < 4 * end:
            cuts = sorted(set(cuts) | {1 + (step * 37 + at) % (end - 1)})
            step += 1
        bounds = [0] + cuts[: rows - 1] + [end]
        out += [[(bounds[k], bounds[k + 1], "1" if time is not None and bounds[k] >= time else "0", found.ended[at] if k == len(bounds) - 2 else "0") for k in range(len(bounds) - 1)]]
    return out


def _file(histories: "list[list[tuple[int, int, str, str]]]") -> "tuple[list[list[int]], list[object], list[object], dict[str, list[str]]]":
    rows_of: "list[list[int]]" = []
    start: "list[object]" = []
    stop: "list[object]" = []
    texts: "dict[str, list[str]]" = {"s": [], "e": []}
    for mine in histories:
        held: "list[int]" = []
        for a, b, switch, end in mine:
            held += [len(start)]
            start += [fractions.Fraction(a)]
            stop += [fractions.Fraction(b)]
            texts["s"] += [switch]
            texts["e"] += [end]
        rows_of += [held]
    return rows_of, start, stop, texts


