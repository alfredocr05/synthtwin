# -- THE FLOORS AND ROUNDINGS OF THE PUBLISHED FACTS, MACHINE-FREE (repair 1, item 2; HIPAA) ----------------------


START_RUNGS = [10, 25, 60, 120]
STOP_RUNGS = [15, 40, 90, 200]
# A patient-fixed column's bands: four at L0, three at L1, two at L2.
COLUMN_MAPS = ((0, 1, 2, 3), (0, 0, 1, 2), (0, 0, 1, 1))


def _rung_block(rungs: "list[int]") -> dict:
    return {"role": "count", "percentiles": {f"p{10 * (at + 1)}": value for at, value in enumerate(rungs)}}


def _rung_scale(name: str, count: int) -> chain_rules.Ladder:
    keys = [f"p{10 * (at + 1)}" for at in range(count)]
    bounds: "list[object]" = [None, *keys, None]
    l0 = tuple(((bounds[at], bounds[at + 1]),) for at in range(len(bounds) - 1))
    same = tuple(range(len(l0)))
    return chain_rules.Ladder(name, l0, (same, same, same), (len(l0),) * 3, tuple(1 for _band in l0), tuple(True for _band in l0))


def _generated_found(draw: random.Random, kind: str) -> "tuple[patient_intervals.Found, list[int]]":
    """An invented `Found` of 60 to 400 patients and its column's `L0` codes, shaped so `kind` puts a count of 1 to f - 1 where it names."""
    patients = draw.randint(60, 400)
    follow = [fractions.Fraction(draw.randint(1, 400)) for _patient in range(patients)]
    ended = [draw.choice("0011122") for _patient in range(patients)]
    switched: "list[fractions.Fraction | None]" = [
        None if draw.random() < 0.4 else fractions.Fraction(draw.randint(0, int(follow[at]) - 1)) for at in range(patients)
    ]
    codes = [draw.choice((0, 1, 1, 2, 2, 3, 3)) for _patient in range(patients)]
    few = draw.randint(1, FLOOR - 1)
    if kind == "never":
        switched = [time if at >= few else None for at, time in enumerate(switched)]
        switched = [fractions.Fraction(draw.randint(0, int(follow[at]) - 1)) if at >= few and time is None else time for at, time in enumerate(switched)]
    elif kind == "switched":
        switched = [fractions.Fraction(draw.randint(0, int(follow[at]) - 1)) if at < few else None for at in range(patients)]
    elif kind == "state":
        changed = [at for at in range(patients) if switched[at] is not None and ended[at] == "2"]
        for at in changed[few:]:
            ended[at] = "1"
    elif kind == "column":
        held = [at for at in range(patients) if codes[at] == 3]
        for at in held[few:]:
            codes[at] = 2
    elif kind in ("band_switched", "band_never"):
        # Band 3's switched (or never-switched) patients 1 to f - 1, the rest of the band the other way (repair 2, the
        # verify's item 2; LANE GRb2 RULINGS 11 (2)).
        third = [at for at in range(patients) if codes[at] == 3]
        for place, at in enumerate(third):
            turned = place < few if kind == "band_switched" else place >= few
            switched[at] = fractions.Fraction(draw.randint(0, int(follow[at]) - 1)) if turned else None
    found = patient_intervals.Found("a", "b", 0, ("s", "0", "1"), ("e", "0", ("0", "1", "2")), follow, switched, ended, [[] for _patient in range(patients)])
    return found, codes


def _person_time(follow: "list[fractions.Fraction]", lows: "list[fractions.Fraction]") -> "list[fractions.Fraction]":
    """Each patient's time from 0 to its follow-up, summed in each band cut at `lows[1:]` (exact)."""
    out = [fractions.Fraction(0) for _band in lows]
    for end in follow:
        for band in range(len(lows)):
            high = lows[band + 1] if band + 1 < len(lows) else None
            if end > lows[band]:
                out[band] += (end if high is None or end < high else high) - lows[band]
    return out


def _passes(cells: "list[list[int]]") -> bool:
    people = [sum(line[band] for line in cells) for band in range(len(cells[0]))]
    return all(cell == 0 or cell >= FLOOR for line in cells for cell in line) and all(one == 0 or one >= FLOOR for one in people)


def test_every_published_count_holds_the_floor_and_every_figure_its_rounding_over_generated_facts():
    """Over 1,800 generated `Found` tables (repair 1, item 2, and repair 2, the verify's item 2; HIPAA), each shaped to put a count of 1 to f - 1 in one place.

    (a) the patients who never switch held by 1 to f - 1: the switch's
    bands are withheld; (b) the switched patients 1 to f - 1: withheld;
    (c) a cell of the switch's two states 1 to f - 1: that margin
    withheld; (d) a column's `L0` and `L1` cells holding 1 to f - 1: the
    column published at the finest level whose every cell and band holds
    0 or at least f, or dropped; (e) one band's switched patients 1 to f
    - 1, the rest of it never switching, and (f) one band's never-switched
    1 to f - 1: the column's `switches` absent at its published level
    wherever its band reads so; every count published 0 or at least f;
    every person-time the exact sum to three significant figures; the top
    band's mean the exact mean to one place more than the column's.
    Mutants, one by one: `_switch_entry` without its never floor, without
    its totals floor or without its top mean's rounding; `published`
    without the switch margin's floor, without the column floor or
    without person-time's rounding; the column's switches without their
    floors (the verify's X1 and X2).
    """
    draw = random.Random(4917)
    blocks = {"a": _rung_block(START_RUNGS), "b": _rung_block(STOP_RUNGS)}
    scales = {"a": _rung_scale("a", len(START_RUNGS)), "b": _rung_scale("b", len(STOP_RUNGS))}
    ladder = chain_rules.Ladder("band", tuple(((f"b{at}",),) for at in range(4)), COLUMN_MAPS, (4, 3, 2), (1, 1, 1, 1), (False,) * 4)
    seen = {"never": 0, "switched": 0, "state": 0, "column": 0, "band_switched": 0, "band_never": 0}
    for case in range(1800):
        kind = ("never", "switched", "state", "column", "band_switched", "band_never")[case % 6]
        found, codes = _generated_found(draw, kind)
        levels = [[COLUMN_MAPS[level][code] for code in codes] for level in range(3)]
        out = patient_intervals.published(found, blocks, scales, [("band", ladder, (levels[0], levels[1], levels[2]))], FLOOR)
        if out is None:
            continue
        seen[kind] += 1
        values = ["0", "1", "2"]
        never = sum(1 for time in found.switched if time is None)
        changed = [time for time in found.switched if time is not None]
        switches = out["switches"]
        assert all(one == 0 or one >= FLOOR for one in _every_count(out)), (case, kind)
        if 0 < never < FLOOR or 0 < len(changed) < FLOOR:
            assert switches == [], (case, kind)
        if switches:
            entry = switches[0]
            assert entry["never"] == never and sum(entry["patients"]) == len(changed)
            edges = [fractions.Fraction(one) for one in entry["edges"]]
            top = [time for time in changed if not edges or time >= edges[-1]]
            exact = sum(top, fractions.Fraction(0)) / len(top)
            assert fractions.Fraction(entry["top_mean"]) == fractions.Fraction(round(exact * 10), 10), (case, kind)
            assert len(f"{entry['top_mean']}".partition(".")[2]) <= found.places + 1
        hazard = out["hazard"]
        lows = [fractions.Fraction(0)] + [fractions.Fraction(one) for one in hazard["edges"]]
        assert hazard["person_time"] == [patient_rules.decimal_text(patient_intervals.significant(one)) for one in _person_time(found.follow, lows)], (case, kind)
        state = [[0, 0] for _value in values]
        time_before = time_after = fractions.Fraction(0)
        for at, end in enumerate(found.follow):
            time = found.switched[at]
            state[values.index(found.ended[at])][1 if time is not None and time < end else 0] += 1
            time_before += time if time is not None and time < end else end
            time_after += end - time if time is not None and time < end else 0
        if switches and all(cell == 0 or cell >= FLOOR for line in state for cell in line) and sum(line[1] for line in state) >= FLOOR:
            assert hazard["switch"] == {
                "events": state,
                "person_time": [patient_rules.decimal_text(patient_intervals.significant(time_before)), patient_rules.decimal_text(patient_intervals.significant(time_after))],
            }, (case, kind)
        else:
            assert hazard["switch"] is None, (case, kind)
        finest = None
        for level in range(3):
            cells = [[0] * (4, 3, 2)[level] for _value in values]
            for at in range(len(codes)):
                cells[values.index(found.ended[at])][levels[level][at]] += 1
            if _passes(cells):
                finest = (level, cells)
                break
        if finest is None:
            assert hazard["columns"] == [], (case, kind)
        else:
            level, cells = finest
            times = [fractions.Fraction(0)] * (4, 3, 2)[level]
            turned = [0] * (4, 3, 2)[level]
            for at in range(len(codes)):
                times[levels[level][at]] += found.follow[at]
                turned[levels[level][at]] += 1 if found.switched[at] is not None else 0
            expected: "dict[str, object]" = {
                "column": "band", "events": cells, "level": chain_rules.LEVELS[level],
                "person_time": [patient_rules.decimal_text(patient_intervals.significant(one)) for one in times],
            }
            people = [sum(line[band] for line in cells) for band in range(len(turned))]
            if switches and all(one == 0 or one >= FLOOR for one in turned + [people[band] - turned[band] for band in range(len(turned))]):
                expected["switches"] = turned
            assert hazard["columns"] == [expected], (case, kind)
    assert all(count >= 150 for count in seen.values()), seen


