def test_a_switch_of_few_changers_or_an_end_rule_of_a_rare_none_is_withheld_over_generated_tables():
    """Over 400 generated tables at the floor (repair 1, item 5): a switch made by 1 to f - 1 changers publishes no switch rule, and a none spelling held by 1 to f - 1 patients publishes no end rule, though every spelling is held by at least f patients; with f changers (or f holders of none) each stands.

    Mutants: `_switch_of` without its test of the changers; `_end_of`
    without the none spelling's patient floor.
    """
    draw = random.Random(4916)
    misread: "list[tuple[int, str, int]]" = []
    for case in range(400):
        few = draw.randint(1, FLOOR)
        if case % 2 == 0:
            # `few` changers from 0 to 1; FLOOR patients at 1 from their first row (no change); others at 0 throughout.
            table = [[(0, 4, "0", "0"), (4, 9, "1", draw.choice("12"))] for _one in range(few)]
            table += [[(0, 5, "1", "0"), (5, 8, "1", draw.choice("12"))] for _one in range(FLOOR)]
            table += [[(0, 6, "0", "0"), (6, 7, "0", draw.choice("12"))] for _one in range(draw.randint(FLOOR, 40))]
            found = _found(table, FLOOR)
            stands = found is not None and found.switch is not None
            if stands != (few >= FLOOR):
                misread += [(case, "switch", few)]
        else:
            # `few` patients of two rows (none on the first); every other patient one row ending 1 or 2; none ends 0.
            table = [[(0, 3, "0", "0"), (3, 9, "0", "1")] for _one in range(few)]
            table += [[(0, draw.randint(1, 30), "0", value)] for value in "12" for _one in range(draw.randint(FLOOR, 40))]
            found = _found(table, FLOOR)
            stands = found is not None and found.end is not None
            if stands != (few >= FLOOR):
                misread += [(case, "end", few)]
    assert misread == []


def test_bands_merge_until_every_count_holds_the_floor_over_a_generated_sweep():
    """Over 3,000 generated band tables: every merged band's counts are 0 or at least the floor and its total at least the floor; a band that passes alone is kept alone. Mutant: the merge's test of a band always passing."""
    draw = random.Random(4914)
