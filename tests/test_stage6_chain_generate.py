def _comma_table(rows: int) -> str:
    """Codex's table (lane CHb's second repair, its item 1): a measurement written with a decimal
    comma, `10,0` to ..., every tenth row `low`, beside a group alternating `b` and `a`."""
    lines = ["group,value"]
    for row in range(rows):
        value = f"{10 + row * 0.1:.1f}".replace(".", ",") if row % 10 < 9 else "low"
        lines += [("b" if row % 2 == 0 else "a") + ',"' + value + '"']
    return "\n".join(lines) + "\n"


