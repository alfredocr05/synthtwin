def _holding_nothing(switched: _Switched, twin: generation.Twin) -> int:
    held = [list(generation.twin_column(twin, place)) for place in range(generation.twin_width(twin))]
    return sum(1 for row in range(twin.n_rows) if all(dialect.holds_nothing(column[row]) for column in held))


def test_a_published_nought_holding_a_row_is_caught(ward: _Switched, monkeypatch: pytest.MonkeyPatch) -> None:
    """MUTANT: the target of a family holding a published nought moves one row into it (the
    row taken from the largest cell of the same parent cell, its band given back where the
    nought's band lost it). The same checks find the family off and a row in a nought."""
    noughts = [family["child"] for family in ward.statistical["chain"]  # type: ignore[union-attr]
               if family["parents"] and any(0 in row and sum(row) for row in family["table"])]
    assert noughts, "the ward's chain publishes a nought beside a parent"
    real = chain_walk.target_of

    def shifted(published, parent_counts, child_totals):  # type: ignore[no-untyped-def]
        found = real(published, parent_counts, child_totals)
        rows = [list(row) for row in found.table]
        for first in range(len(rows)):
            if 0 in rows[first] and sum(rows[first]):
                hole = rows[first].index(0)
                full = rows[first].index(max(rows[first]))
                for second in range(len(rows)):
                    if second != first and rows[second][hole] > 0 and rows[second][full] >= 0:
                        rows[first][hole] += 1
                        rows[first][full] -= 1
                        rows[second][hole] -= 1
                        rows[second][full] += 1
                        return chain_walk.Target(tuple(tuple(row) for row in rows), found.moved, found.noughts)
        return found

    monkeypatch.setattr(chain_walk, "target_of", shifted)
    twin = generation.generate_held(ward.loaded, 0)
    assert _families_off(ward, twin) != []
    assert _noughts_held(ward, twin) > 0


def test_a_family_s_cell_off_by_one_row_is_caught(assoc: _Switched, monkeypatch: pytest.MonkeyPatch) -> None:
    """MUTANT: after each family is dealt, two rows of different bands in different parent
    cells exchange their cell indices, every band total kept. The family check finds it."""
    real = chain_walk.deal

    def swapped(cells, cell_count, order, child, target):  # type: ignore[no-untyped-def]
        dealt = real(cells, cell_count, order, child, target)
        if cell_count < 2:
            return dealt
        width = dealt.index_width
        first = 0
        band = chain_walk.read_code(dealt.bands, dealt.band_width, first)
        for second in range(1, chain_walk.size_of(cells)):
            if chain_walk.item(cells, second) != chain_walk.item(cells, first) and chain_walk.read_code(dealt.bands, dealt.band_width, second) != band:
                index = bytearray(dealt.index)
                left = index[first * width:(first + 1) * width]
                index[first * width:(first + 1) * width] = index[second * width:(second + 1) * width]
                index[second * width:(second + 1) * width] = left
                return dataclasses.replace(dealt, index=index)
        return dealt

    monkeypatch.setattr(chain_walk, "deal", swapped)
    assert _families_off(assoc, generation.generate_held(assoc.loaded, 0)) != []


def test_a_child_placed_against_the_wrong_parent_band_is_caught(assoc: _Switched, monkeypatch: pytest.MonkeyPatch) -> None:
    """MUTANT: each family's child is placed by its index as dealt, but the band codes later
    families read for it stand one row off, so every later family is dealt against parent
    bands that are not the twin's. Its tables are off where they are read back."""
    real = chain_walk.deal

    def shifted(cells, cell_count, order, child, target):  # type: ignore[no-untyped-def]
        dealt = real(cells, cell_count, order, child, target)
        width = dealt.band_width
        bands = bytearray(dealt.bands[width:] + dealt.bands[:width])
        return dataclasses.replace(dealt, bands=bands)

    monkeypatch.setattr(chain_walk, "deal", shifted)
    assert _families_off(assoc, generation.generate_held(assoc.loaded, 0)) != []


