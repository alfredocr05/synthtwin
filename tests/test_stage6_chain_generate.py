# -- reading a twin back the way the profile reads a table ---------------------------


def _written(switched: _Switched, twin: generation.Twin) -> pathlib.Path:
    out = switched.folder / "twin.csv"
    out.write_text("".join(rendering.twin_csv_pieces(twin)), encoding="utf-8", newline="")
    return out


_READ_BACK: "dict[int, tuple[generation.Twin, dict[str, tuple[list[int], list[list[int]], list[int]]]]]" = {}


def _codes_back(switched: _Switched, twin: generation.Twin) -> "dict[str, tuple[list[int], list[list[int]], list[int]]]":
    """Each eligible column's `L0` band on each tabled row of the twin, its level maps and band counts.
    A twin is read back once for the file, the reading kept beside the twin it was read from."""
    kept = _READ_BACK.get(id(twin))
    if kept is not None and kept[0] is twin:
        return kept[1]
    out = _codes_read(switched, twin)
    _READ_BACK[id(twin)] = (twin, out)
    return out


def _codes_read(switched: _Switched, twin: generation.Twin) -> "dict[str, tuple[list[int], list[list[int]], list[int]]]":
    back = reading.read_table(str(_written(switched, twin)), small_cell_floor=FLOOR)
    blocks: "dict[str, tuple[int, dict[str, object]]]" = {}
    for place, block in enumerate(switched.document["columns"]):  # type: ignore[arg-type]
        blocks[f"{block['name']}"] = (place, block)
    blank = chain_rules.records_holding_nothing(switched.document)
    held = [reading.column_values(back, place) for place in range(len(back.column_names))]
    skipped: "set[int]" = set()
    for row in range(back.n_rows):
        if len(skipped) < blank and all(dialect.holds_nothing(column[row]) for column in held):
            skipped |= {row}
    held = []
    out: "dict[str, tuple[list[int], list[list[int]], list[int]]]" = {}
    for entry in switched.statistical["ladder"]:  # type: ignore[union-attr]
        place, block = blocks[entry["column"]]
        read = chain.read_column(back, place, block, switched.settings, SPELLED, "", blank)
        assert read is not None
        to_l0: "dict[object, int]" = {}
        for band, names in enumerate(entry["l0"]):
            for item in names:
                to_l0[tuple(item) if isinstance(item, list) else item] = band
        maps = [list(range(len(entry["l0"]))), [0] * len(entry["l0"]), [0] * len(entry["l0"])]
        for level, key in ((1, "l1"), (2, "l2")):
            for band, members in enumerate(entry[key]):
                for member in members:
                    maps[level][member] = band
        rows: "list[int]" = []
        for row in range(back.n_rows):
            if row in skipped:
                continue
            start = read.start.names[read.codes[row]] if read.codes[row] >= 0 else None
            rows += [to_l0[start] if start in to_l0 else -1]
        out[entry["column"]] = (rows, maps, [len(entry["l0"]), len(entry["l1"]), len(entry["l2"])])
    return out


def _family_tables(switched: _Switched, twin: generation.Twin) -> "list[list[list[int]]]":
    """Each family's table in the twin at its published levels, one row a parent cell."""
    codes = _codes_back(switched, twin)
    out: "list[list[list[int]]]" = []
    for family in switched.statistical["chain"]:  # type: ignore[union-attr]
        rows, maps, counts = codes[family["child"]]
        level = int(family["level"][1])
        parents = [(p["column"], int(p["level"][1])) for p in family["parents"]]
        cells = 1
        for name, parent_level in parents:
            cells *= codes[name][2][parent_level]
        table = [[0] * counts[level] for _ in range(cells)]
        for row in range(len(rows)):
            assert rows[row] >= 0
            cell = 0
            for name, parent_level in parents:
                parent_rows, parent_maps, parent_counts = codes[name]
                assert parent_rows[row] >= 0
                cell = cell * parent_counts[parent_level] + parent_maps[parent_level][parent_rows[row]]
            table[cell][maps[level][rows[row]]] += 1
        out += [table]
    return out


def _families_off(switched: _Switched, twin: generation.Twin) -> "list[str]":
    """The families whose table in the twin is not their published table, by child."""
    tables = _family_tables(switched, twin)
    return [
        family["child"]
        for family, table in zip(switched.statistical["chain"], tables)  # type: ignore[union-attr]
        if table != family["table"]
    ]


def _noughts_held(switched: _Switched, twin: generation.Twin) -> int:
    """The twin's rows standing in a published nought of any family."""
    held = 0
    for family, table in zip(switched.statistical["chain"], _family_tables(switched, twin)):  # type: ignore[union-attr]
        for place in range(len(table)):
            for band in range(len(table[place])):
                if family["table"][place][band] == 0:
                    held += table[place][band]
    return held


def _rates_and_odds(published: "list[list[int]]", found: "list[list[int]]") -> "tuple[int, int, int, int]":
    """Every rate (a cell over its parent cell's rows) and every odds ratio of two bands in two
    parent cells at the published levels, compared exactly: (rates checked, rates off, odds
    ratios checked, odds ratios off)."""
    rates = rates_off = odds = odds_off = 0
    for place in range(len(published)):
        total = sum(published[place])
        found_total = sum(found[place])
        for band in range(len(published[place])):
            if total:
                rates += 1
                if found_total == 0 or published[place][band] * found_total != found[place][band] * total:
                    rates_off += 1
    width = len(published[0]) if published else 0
    for first in range(len(published)):
        for second in range(first + 1, len(published)):
            for low in range(width):
                for high in range(low + 1, width):
                    cells = (published[first][low], published[first][high], published[second][low], published[second][high])
                    if 0 in cells:
                        continue
                    odds += 1
                    left = published[first][low] * published[second][high] * found[first][high] * found[second][low]
                    right = published[first][high] * published[second][low] * found[first][low] * found[second][high]
                    if left != right:
                        odds_off += 1
    return rates, rates_off, odds, odds_off


