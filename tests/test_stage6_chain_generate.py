def _product_starts(band: "list[object]") -> "list[object]":
    out: "list[object]" = []
    for start in band:
        if isinstance(start, tuple) and start[0] == "range":
            out += [(start[1], start[2])]
        elif isinstance(start, tuple) and start[0] == "level":
            out += ["held back" if start[1] == "held back" else (start[1],)]
        else:
            out += [start]
    return out


def _product_walk(chain_, lads, twin, words, slopes=None, codes=None, targets=None):  # type: ignore[no-untyped-def]
    """The shared module's walk on the oracle's inputs: what `generation` does, one family at a time."""
    slopes = slopes or {}
    codes = codes or {}
    targets = targets or {}
    n = len(words[0])
    band_codes: "dict[str, list[int]]" = {}
    readings: "dict[str, list[object]]" = {}
    index: "dict[str, list[int]]" = {}
    lists: "dict[str, list[tuple[str, object]]]" = {}
    dealt_tables = []
    level_of = {fam.child: fam.level for fam in chain_}
    for at, fam in enumerate(chain_):
        lad = lads[fam.child]
        bands = lad.bands(fam.level)
        listing: "list[tuple[str, object]]" = []
        sizes: "list[int]" = []
        read: "list[int]" = []
        ordered: "list[bool]" = []
        for members in bands:
            holding = []
            empty = []
            rank = 0
            for l0 in members:
                for text, value in twin[fam.child][l0]:
                    if value is None:
                        empty += [(text, value)]
                    else:
                        holding += [(value, rank, text)]
                    rank += 1
            listing += [(text, value) for value, _rank, text in sorted(holding)] + empty
            sizes += [len(holding) + len(empty)]
            read += [len(holding)]
            ordered += [any(generation._value_start(s) for l0 in members for s in _product_starts(lad.l0[l0]))]
        child = chain_walk.ChildBands(tuple(sizes), tuple(read), tuple(ordered))
        cells = [0] * n
        cell_count = 1
        for parent, parent_level in fam.parents:
            down = {b: lads[parent].coarsen(parent_level)[members[0]] for b, members in enumerate(lads[parent].bands(level_of[parent]))}
            size = len(lads[parent].bands(parent_level))
            cell_count *= size
            for r in range(n):
                cells[r] = cells[r] * size + down[band_codes[parent][r]]
        counts = [cells.count(c) for c in range(cell_count)]
        if at in targets:
            target = tuple(tuple(row) for row in targets[at])
        else:
            target = chain_walk.target_of(tuple(tuple(row) for row in fam.table), counts, sizes).table
        sums = [chain_walk.hidden_sum(*words[at][r]) for r in range(n)]
        if at in slopes and slopes[at] is not None:
            parent_terms, sigma_text = slopes[at]
            terms = []
            for parent, beta_text in parent_terms:
                lo, hi = codes[parent]
                value_codes = bytearray(n)
                mapped = bytearray(n)
                for r in range(n):
                    value = readings[parent][r]
                    if value is not None:
                        value_codes[r] = chain_walk.value_code(float(value), float(lo), float(hi))
                        mapped[r] = 1
                terms += [chain_walk.Slope(value_codes, mapped, float(beta_text))]
            latent = chain_walk.slope_latent(cells, terms, float(sigma_text), sums)
            order = chain_walk.order_by_latent(latent)
        else:
            order = chain_walk.order_by_scores(sums)
        dealt = chain_walk.deal(cells, cell_count, order, child, target)
        band_codes[fam.child] = [chain_walk.read_code(dealt.bands, dealt.band_width, r) for r in range(n)]
        index[fam.child] = [chain_walk.read_code(dealt.index, dealt.index_width, r) for r in range(n)]
        lists[fam.child] = listing
        readings[fam.child] = [listing[index[fam.child][r]][1] for r in range(n)]
        dealt_tables += [[list(row) for row in dealt.table]]
    return index, lists, dealt_tables


