def _association(rows: int, seed: int = 5) -> str:
    """K-S6-01's table (`tests/kpi_shapes.association_table`) at ``rows`` rows: sbp built from age, death depending on age."""
    draw = random.Random(seed)
    lines = ["age,sbp,group,died"]
    for _ in range(rows):
        age = draw.gauss(55, 12)
        sbp = 100 + 0.8 * age + draw.gauss(0, 8)
        group = draw.choice("FM")
        died = "yes" if draw.random() < (0.6 if age > 65 else 0.1) else "no"
        lines += [f"{age:.0f},{sbp:.0f},{group},{died}"]
    return "\n".join(lines) + "\n"


def _ward(rows: int) -> str:
    """An invented ward: a stay, a lab with `NA`, a gender, a pregnancy asked of women only, an
    admission date and an arrival time; some records hold nothing (E > 0)."""
    draw = random.Random(20261025)
    lines = ["record,stay,lab,gender,pregnant,admit_date,arrival"]
    for place in range(rows):
        if draw.random() < 0.004:
            lines += [",,,,,,"]
            continue
        gender = draw.choice(["F", "M"])
        stay = 0 if draw.random() < 0.2 else min(int(draw.lognormvariate(1.3, 1.0)), 300)
        lab = "NA" if draw.random() < 0.03 else f"{draw.lognormvariate(1.5, 0.5):.2f}"
        pregnant = "" if gender == "M" else ("yes" if draw.random() < 0.08 + 0.002 * stay else "no")
        day = 738156 + draw.randint(0, 2 * 365)
        year, month, date = _civil(day)
        minutes = int(min(max(draw.gauss(14 * 60, 180), 0), 1439))
        lines += [f"R{place:07d},{stay},{lab},{gender},{pregnant},{year:04d}-{month:02d}-{date:02d},{minutes // 60:02d}:{minutes % 60:02d}"]
    return "\n".join(lines) + "\n"


def _civil(ordinal: int) -> "tuple[int, int, int]":
    import datetime

    day = datetime.date.fromordinal(ordinal)
    return day.year, day.month, day.day


@dataclasses.dataclass
class _Switched:
    path: pathlib.Path
    document: "dict[str, object]"
    statistical: "dict[str, object]"
    loaded: contract.Profile
    plain: contract.Profile
    settings: taxonomy.Settings
    folder: pathlib.Path
    twins: "dict[int, generation.Twin]"
    emptied: "dict[int, generation.Twin]" = dataclasses.field(default_factory=dict)

    def twin(self, seed: int) -> generation.Twin:
        if seed not in self.twins:
            self.twins[seed] = generation.generate_held(self.loaded, seed)
        return self.twins[seed]

    def layered(self) -> generation.Twin:
        """The twin at seed 0 of the switched description with its chain emptied (lane BT's layer L0
        alone), made once for the file."""
        if 0 not in self.emptied:
            self.emptied[0] = generation.generate_held(dataclasses.replace(
                self.loaded, relationships=dataclasses.replace(self.loaded.relationships, chain=())), 0)
        return self.emptied[0]


def _switched(folder: pathlib.Path, name: str, text: str) -> _Switched:
    """The table described with the chain's switch (a fixed test key), loaded behind it and without it."""
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / f"{name}.csv"
    path.write_text(text, encoding="utf-8", newline="\n")
    settings = taxonomy.Settings(small_cell_floor=FLOOR)
    table = reading.read_table(str(path), small_cell_floor=FLOOR)
    document = profile.build_document(table, settings, [], [], [])
    # THE GRAIN STATED (lane GRa, plan P4-D449): `K-S6-03`'s driver and this file
    # measure the WALK, beside a repeating column too; no question is put here.
    chained = chain.describe(table, document, settings, chain.ChainSwitch(name, TEST_KEY, rows_per_person=chain.ROWS_UNASKED))
    assert chained.statistical is not None, chained.notes
    written = dict(document)
    relationships = dict(written["relationships"])  # type: ignore[call-overload]
    relationships["statistical"] = chained.statistical
    written["relationships"] = relationships
    on = fixtures.write_profile(folder, f"{name}-switched.json", written)
    off = fixtures.write_profile(folder, f"{name}-plain.json", document)
    return _Switched(
        path, written, chained.statistical, contract.load_profile(str(on), chain=True),
        contract.load_profile(str(off)), settings, folder, {},
    )


