def test_every_family_is_met_on_the_association_table(assoc: _Switched) -> None:
    """K-S6-01's table at the owner's floor, 20,000 rows: age, sbp, group and died, each the
    child of one family. Read back by the profile's own reader, every family's table at its
    published levels equals the published table cell for cell, so every rate and every odds
    ratio at those levels is the real table's, and every L0 band total is met. One seed here, the
    one the mutants below take (the suite's time, the orchestrator's rule of 2026-10-26); seeds 0 to 4
    at 20,000 and 200,000 rows are K-S6-03's driver's."""
    twin = assoc.twin(0)
    assert _families_off(assoc, twin) == []
    assert not [note for note in twin.deviations if note.fact in ("chain", "empty_rows")]
    tables = _family_tables(assoc, twin)
    checked = 0
    for family, table in zip(assoc.statistical["chain"], tables):  # type: ignore[union-attr]
        rates, rates_off, odds, odds_off = _rates_and_odds(family["table"], table)
        assert (rates_off, odds_off) == (0, 0)
        checked += rates + odds
    assert checked > 0
    with_parent = [family for family in assoc.statistical["chain"] if family["parents"]]  # type: ignore[union-attr]
    assert with_parent, "the fixture's chain places a family with a parent"


