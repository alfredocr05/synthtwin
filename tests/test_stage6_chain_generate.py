def _ward_book(rows: int) -> bytes:
    """The gate's ward as a workbook (stay, lab, gender, pregnant), as lane BT's battery builds its own:
    shared strings for words, numbers as numbers, the records holding nothing formatted blank cells."""
    import workbooks

    lines = _ward(rows).strip("\n").split("\n")[1:]
    picked = [1, 2, 3, 4]
    names = ["stay", "lab", "gender", "pregnant"]
    strings = list(names) + ["NA", "F", "M", "yes", "no"]
    index_of = {text: place for place, text in enumerate(strings)}
    letters = "ABCD"
    sheet_rows = [(1, [workbooks.cell(f"{letters[k]}1", str(k), "s") for k in range(4)])]
    for place, line in enumerate(lines):
        number = place + 2
        row = line.split(",")
        if not any(row):
            sheet_rows += [(number, [workbooks.cell(f"{letters[k]}{number}", "", "", workbooks.HEADER_STYLE) for k in range(4)])]
            continue
        cells = []
        for k in range(4):
            text = row[picked[k]]
            if text == "":
                continue
            cells += [workbooks.cell(f"{letters[k]}{number}", str(index_of[text]), "s") if text in index_of
                      else workbooks.cell(f"{letters[k]}{number}", text)]
        sheet_rows += [(number, cells)]
    return workbooks.package([
        ("[Content_Types].xml", workbooks._content_types(1, True, False, False)),
        ("_rels/.rels", workbooks._root_rels()),
        ("xl/workbook.xml", workbooks._workbook([("Data", "")])),
        ("xl/_rels/workbook.xml.rels", workbooks._workbook_rels(1, True)),
        ("xl/styles.xml", workbooks._styles()),
        ("xl/sharedStrings.xml", workbooks._shared_strings(strings)),
        ("xl/worksheets/sheet1.xml", workbooks.sheet(sheet_rows, dimension=f"A1:D{len(lines) + 1}")),
    ])


