# -- the oracle, cell for cell ---------------------------------------------------------


def _oracle_ladder(entry: "dict[str, object]", role: str) -> object:
    """The oracle's ladder of a published entry: its starting bands in the oracle's form."""
    l0 = []
    for band in entry["l0"]:  # type: ignore[union-attr]
        starts = []
        for item in band:
            if isinstance(item, list) and len(item) == 2:
                starts += [("range", item[0], item[1])]
            elif isinstance(item, list) and len(item) == 1:
                starts += [("level", item[0])]
            elif item == "held back":
                starts += [("level", "held back")]
            else:
                starts += [item]
        l0 += [starts]
    ordered = [any(isinstance(s, tuple) for s in band) for band in l0]
    return co.Ladder(entry["column"], role, l0, list(entry["totals"]), entry["l1"], entry["l2"], [], [], ordered)


def _interface_kind(found: generation.BandCells, group: int, rank: int, label: bool) -> object:
    name = found.names[group]
    if name == "range":
        return ("range", rank)
    if name == "level":
        lowers = found.lowers[group]
        return ("level", lowers[0]) if isinstance(lowers, tuple) else ("level", None)
    return name


def test_the_twin_is_the_oracle_s_arrangement_cell_for_cell(assoc: _Switched, monkeypatch: pytest.MonkeyPatch) -> None:
    """The product's twin at 20,000 rows against the oracle's walk (`co.walk_rows`) on the same
    interface cells (`generation.cells_by_band`, joined into L0 bands by the oracle's own
    reading, `co.interface_bands`) and the same words: every row holds, in every eligible
    column, the cell the oracle puts there, and every family's table as dealt is the oracle's.
    The cells and the words are taken from the product's own run, never computed here."""
    captured: "dict[str, tuple[generation.BandCells, list[str]]]" = {}
    words: "list[list[int]]" = []
    real_cells = generation.cells_by_band
    real_sums = chain_walk.hidden_sums

    def cells(profile_, step, content, drawn, reserved, readings):  # type: ignore[no-untyped-def]
        found = real_cells(profile_, step, content, drawn, reserved, readings)
        if found is not None:
            captured[found.column] = (found, list(content))
        return found

    def sums(given):  # type: ignore[no-untyped-def]
        words[len(words):] = [list(given)]
        return real_sums(given)

