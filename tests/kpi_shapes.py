# -- one whole run, in process ------------------------------------------


class Described:
    """A table on disk, its description document and the loaded profile."""

    def __init__(
        self,
        folder: pathlib.Path,
        table: pathlib.Path,
        document: "dict",
        loaded: contract.Profile,
    ) -> None:
        self.folder = folder
        self.table = table
        self.document = document
        self.loaded = loaded

    def block(self, name: str) -> "dict":
        """The description block of one named column."""
        for block in self.document["columns"]:
            if block["name"] == name:
                return block
        raise AssertionError(f"no column {name!r}")


def describe(
    folder: pathlib.Path,
    stem: str,
    text: str,
    floor: "int | None" = None,
    declared: "list[str] | None" = None,
    codes: "list[str] | None" = None,
    measured: "list[str] | None" = None,
    first_row: str = reading.FIRST_ROW_AUTOMATIC,
) -> Described:
    """Write ``text`` as a table and describe it; ``floor`` None is the shipped default."""
    folder.mkdir(parents=True, exist_ok=True)
    table = fixtures.write(folder, f"{stem}.csv", text)
    settings = (
        taxonomy.Settings()
        if floor is None
        else taxonomy.Settings(small_cell_floor=floor)
    )
    # READ AT THE FLOOR IT IS DESCRIBED AT (plan P4-D317). The reader
    # asks the file's line rules at its own floor, so a table read at one
    # floor and described at another publishes a form no description at
    # the described floor would.
    document = profile.build_document(
        reading.read_table(
            str(table),
            first_row=first_row,
            small_cell_floor=settings.small_cell_floor,
        ),
        settings,
        declared or [],
        codes or [],
        measured or [],
    )
    written = fixtures.write_profile(folder, f"{stem}-profile.json", document)
    return Described(folder, table, document, contract.load_profile(str(written)))


def twin_text(described: Described, seed: int) -> str:
    """The twin's exact bytes, as `synthtwin generate` writes them."""
    return rendering.twin_csv(generation.generate(described.loaded, seed))


def measure(described: Described, text: str, name: str) -> validation.Outcome:
    """Validate a file holding ``text`` against the description."""
    target = fixtures.write(described.folder, name, text)
    return validation.measure(described.loaded, str(target))


def missed(outcome: validation.Outcome) -> "list[str]":
    """Every MISSED verdict as 'column:subcheck', with no carve-out."""
    return sorted(
        f"{check.column}:{check.subcheck}"
        for check in outcome.checks
        if check.verdict == validation.MISSED
    )


def every_role(folder: pathlib.Path, floor: "int | None", headed: bool = True) -> Described:
    """The every-role table with its joined column (tests/test_validation.py's run).

    Headed, the record number is declared and the pressure column is a
    measurement. Headerless, the header line is taken off and the first
    row is declared a record, so nothing can be declared by name.
    """
    text = fixtures.every_role_and_joined_table()
    if headed:
        return describe(
            folder,
            f"every-role-{floor}",
            text,
            floor,
            ["record_code"],
            measured=[fixtures.JOINED_COLUMN],
        )
    bare = text.split("\n", 1)[1]
    return describe(
        folder,
        f"every-role-bare-{floor}",
        bare,
        floor,
        first_row=reading.FIRST_ROW_DATA,
    )


def quiet_cli(argv: "list[str]") -> int:
    """One synthtwin command in this process, its screen output swallowed."""
    before = sys.argv
    sys.argv = ["synthtwin"] + argv
    try:
        with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(
            io.StringIO()
        ):
            try:
                code = cli.main()
            except SystemExit as stop:
                code = 0 if stop.code is None else int(stop.code)
    finally:
        sys.argv = before
    return code


def cycle(
    path: pathlib.Path, flags: "list[str]", seed: str = SHAPE_SEED,
    generate: bool = True, validate: bool = True,
) -> "dict":
    """profile, generate, validate the twin AND the real file, through the command line.

    Returns the four exit codes (None for a step not run) and the paths
    the run left. A measurement that needs only the description, or only
    the twin, asks for less and costs less.
    """
    folder = path.parent
    out: "dict" = {"profile": quiet_cli(
        ["profile", str(path), "--out-dir", str(folder), "--replace", *flags]
    )}
    description = folder / (path.stem + "-profile.json")
    twin = folder / (path.stem + "-twin" + path.suffix)
    out["description"] = description
    out["twin"] = twin
    out["generate"] = out["validate_twin"] = out["validate_real"] = None
    if out["profile"] != 0 or not generate:
        return out
    out["generate"] = quiet_cli(
        ["generate", str(description), "--out-dir", str(folder), "--seed", seed, "--replace"]
    )
    if out["generate"] != 0 or not twin.exists() or not validate:
        return out
    for side, checked in (("validate_twin", twin), ("validate_real", path)):
        report = folder / side
        report.mkdir(exist_ok=True)
        out[side] = quiet_cli(
            ["validate", str(description), "--twin", str(checked), "--out-dir",
             str(report), "--replace"]
        )
    return out


def csv_rows(path: pathlib.Path) -> "list[list[str]]":
    """A delimited file's rows, header included, whatever its mark and byte-order mark."""
    raw = path.read_bytes()
    if raw.startswith(b"\xef\xbb\xbf"):
        raw = raw[3:]
    text = raw.decode("utf-8")
    first = text.split("\n", 1)[0]
    mark = ";" if first.count(";") > first.count(",") else ","
    return list(csv.reader(io.StringIO(text, newline=""), delimiter=mark))


def row_copies(
    real: "list[list[str]]", twin: "list[list[str]]", ignore: "int | None"
) -> "tuple[int, int]":
    """(twin rows equal to a whole real row, twin rows equal to one ignoring a column).

    Both lists start with their header, which is not counted.
    """
    whole = {tuple(row) for row in real[1:]}

    def without(row: "list[str]") -> "tuple[str, ...]":
        return tuple(v for place, v in enumerate(row) if place != ignore)

    partial = {without(row) for row in real[1:]}
    copies = sum(1 for row in twin[1:] if tuple(row) in whole)
    near = sum(1 for row in twin[1:] if without(row) in partial)
    return copies, near


