"""Seeded neutral shapes the KPI ledger measures, and the one whole run each goes through.

Every shape here is built at runtime from a fixed seed (plan D13): no
table enters the repository. Each builder names the ledger entry it
serves, and was ported from the measurement driver that first produced
the entry's number, so the number in `tests/kpi/ledger.json` can be
re-derived by running the test that owns it.

A whole run is the product's own path and nothing else: the table is
written to disk, read by the real reader, described by the real
producer, loaded by the strict loader, generated by the real generator
and checked by the real validator. Nothing is stubbed.
"""

