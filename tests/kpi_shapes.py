def delimited_text(header: "list[str]", rows: "list[list[str]]") -> str:
    """A header and rows as comma-separated text with newline endings."""
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(header)
    writer.writerows(rows)
    return buffer.getvalue()


def privacy_trip(
    folder: pathlib.Path, header: "list[str]", rows: "list[list[str]]",
    flags: "list[str]", seed: str = SHAPE_SEED,
    generate: bool = True, validate: bool = True,
) -> "tuple[dict, list[list[str]], dict]":
    """A command-line run of one small table: (description, twin rows, exits)."""
    folder.mkdir(parents=True, exist_ok=True)
    table = folder / "real.csv"
    table.write_text(delimited_text(header, rows), encoding="utf-8", newline="")
    run = cycle(table, flags, seed, generate, validate)
    document = json.loads(run["description"].read_text("utf-8"))
    twin: "list[list[str]]" = []
    if generate:
        twin = list(csv.reader(io.StringIO(run["twin"].read_text("utf-8"), newline="")))
    exits = {k: run[k] for k in ("profile", "generate", "validate_twin", "validate_real")}
    return document, twin, exits


def room_rows(figures: "int | None") -> "list[list[str]]":
    """1,000 REC-prefixed record numbers of ``figures`` figures, or 989 bare ones."""
    if figures is None:
        return [[f"{i:03d}", "group_x"] for i in range(989)]
    return [[f"REC{i:0{figures}d}", "group_x"] for i in range(1000)]


def subject_rows() -> "list[list[str]]":
    """2,000 SUBJ- record numbers beside a 60-value age column."""
    return [[f"SUBJ-{10000 + i}", f"{20 + (i * 7) % 60}"] for i in range(2000)]


