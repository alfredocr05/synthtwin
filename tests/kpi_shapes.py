EIGHT_ROWS = 400


def _delimited(
    path: pathlib.Path,
    names: "list[str]",
    rows: "list[list[str]]",
    mark: str = ",",
    newline: str = "\n",
    bom: bool = False,
) -> None:
    out = io.StringIO()
    writer = csv.writer(out, delimiter=mark, lineterminator=newline)
    writer.writerow(names)
    writer.writerows(rows)
    data = out.getvalue().encode("utf-8")
    path.write_bytes((b"\xef\xbb\xbf" if bom else b"") + data)


def _plain_styles() -> bytes:
    parts = [
        workbooks._DECLARATION,
        f'<styleSheet xmlns="{workbooks._MAIN}">',
        '<numFmts count="0"></numFmts>',
        '<fonts count="1"><font><sz val="11"/><name val="Calibri"/></font></fonts>',
        '<fills count="2"><fill><patternFill patternType="none"/></fill>'
        '<fill><patternFill patternType="gray125"/></fill></fills>',
        '<borders count="1"><border><left/><right/><top/><bottom/><diagonal/>'
        "</border></borders>",
        '<cellStyleXfs count="1"><xf numFmtId="0" fontId="0" fillId="0" '
        'borderId="0"/></cellStyleXfs>',
        '<cellXfs count="1"><xf numFmtId="0" fontId="0" fillId="0" '
        'borderId="0" xfId="0"/></cellXfs>',
        '<cellStyles count="1"><cellStyle name="Normal" xfId="0" '
        'builtinId="0"/></cellStyles>',
        "</styleSheet>",
    ]
    return "".join(parts).encode("utf-8")


def _workbook(path: pathlib.Path, names: "list[str]", rows: "list[list[str]]") -> None:
    body = [
        (
            1,
            [
                workbooks.cell(f"{workbooks._column(place + 1)}1", name, kind="inlineStr")
                for place, name in enumerate(names)
            ],
        )
    ]
    for place, row in enumerate(rows):
        number = place + 2
        body += [
            (
                number,
                [
                    workbooks.cell(
                        f"{workbooks._column(i + 1)}{number}", value, kind="inlineStr"
                    )
                    for i, value in enumerate(row)
                ],
            )
        ]
    last = f"{workbooks._column(len(names))}{len(rows) + 1}"
    path.write_bytes(
        workbooks.package(
            [
                ("[Content_Types].xml", workbooks._content_types(1, False, False, False)),
                ("_rels/.rels", workbooks._root_rels()),
                ("xl/workbook.xml", workbooks._workbook([("Data", "")])),
                ("xl/_rels/workbook.xml.rels", workbooks._workbook_rels(1, False)),
                ("xl/styles.xml", _plain_styles()),
                ("xl/worksheets/sheet1.xml", workbooks.sheet(body, dimension=f"A1:{last}")),
            ]
        )
    )


def eight_shape_tables() -> "list[dict]":
    """The four families' names, rows, declarations and delimited-file dialect.

    Family A is the files family (semicolons, CRLF, a byte-order mark and
    a declared record number), B the dates family, C the numbers family
    and D the labels family (a declared subject number, a lone re-cased
    label and 'NA' holes).
    """
    draw = random.Random(9)
    out = []
    rows = [
        [f"A-{1000 + i}", draw.choice(["North", "South", "East", "West"]), f"visit {i % 9}"]
        for i in range(EIGHT_ROWS)
    ]
    out += [dict(family="A", names=["record", "site", "note"], rows=rows,
                 identifier="record", mark=";", newline="\r\n", bom=True)]
    first = datetime.date(2021, 1, 1)
    rows = []
    for i in range(EIGHT_ROWS):
        day = first + datetime.timedelta(days=i % 250)
        stamp = day.strftime("%Y-%m-%dT%H:%M:%S").replace(
            "T00:00:00", f"T{8 + i % 9:02d}:{i % 60:02d}:00"
        ) + ("+01:00" if i % 2 else "Z")
        rows += [[day.strftime("%d-%b-%Y"), stamp, draw.choice(["North", "South"])]]
    out += [dict(family="B", names=["taken_on", "seen_at", "site"], rows=rows,
                 identifier=None, mark=",", newline="\n", bom=False)]
    rows = []
    for i in range(EIGHT_ROWS):
        amount = 1000 + i * 7.25
        text = f"{amount:,.2f}"
        if i % 37 == 0:
            text = f"({amount:,.2f})"
        rows += [[text, f"{(i % 40) + 0.5:.1f} mg", draw.choice(["North", "South", "East"])]]
    out += [dict(family="C", names=["amount", "dose", "site"], rows=rows,
                 identifier=None, mark=",", newline="\n", bom=False)]
    labels = (
        ["treated"] * 200 + ["control"] * 180 + ["withdrawn"] * 12
        + ["screen-fail"] * 3 + ["Treated"] * 2 + ["NA"] * 3
    )
    draw.shuffle(labels)
    rows = [
        [f"SUBJ{i:04d}", labels[i], draw.choice(["yes", "no", "n/a"])]
        for i in range(EIGHT_ROWS)
    ]
    out += [dict(family="D", names=["subject", "arm", "outcome"], rows=rows,
                 identifier="subject", mark=",", newline="\n", bom=False)]
    return out


def eight_shapes(home: pathlib.Path, floors: "tuple[int, ...]") -> "list[dict]":
    """Every family, delimited and workbook, through a whole run at each floor."""
    results = []
    for floor in floors:
        for family in eight_shape_tables():
            for kind in ("csv", "xlsx"):
                folder = home / f"{family['family']}_{kind}_{floor}"
                folder.mkdir(parents=True)
                path = folder / f"real.{kind}"
                if kind == "csv":
                    _delimited(path, family["names"], family["rows"], family["mark"],
                               family["newline"], family["bom"])
                else:
                    _workbook(path, family["names"], family["rows"])
                flags = ["--smallest-group", str(floor)]
                if family["identifier"]:
                    flags += ["--identifier", family["identifier"]]
                run = cycle(path, flags)
                run.update(family=family["family"], kind=kind, floor=floor,
                           path=path, family_spec=family)
                results += [run]
    return results


