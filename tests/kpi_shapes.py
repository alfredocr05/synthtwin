def gaussian_table(rows: int, columns: int = 4) -> str:
    """``columns`` Gaussian columns at two decimals (K-S1-07)."""
    draw = random.Random(20260913)
    head = [f"m{c:02d}" for c in range(columns)]
    lines = [",".join(head)]
    for _ in range(rows):
        lines += [",".join(f"{draw.gauss(50 + c, 5 + c % 7):.2f}" for c in range(columns))]
    return "\n".join(lines) + "\n"
