def _at_each_value(twin: generation.Twin, switched: _Switched, name: str) -> "dict[str, int]":
    place = [column.name for column in switched.loaded.columns].index(name)
    held: "dict[str, int]" = {}
    for cell in generation.twin_column(twin, place):
        held[cell] = held.get(cell, 0) + 1
    return held


