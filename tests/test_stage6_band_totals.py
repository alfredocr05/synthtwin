def _ends(facts: contract.NumericFacts, low: float, high: float) -> contract.NumericFacts:
    ladder = facts.percentiles
    rungs = (low,) + ladder.rungs[1:-1] + (high,)
    return dataclasses.replace(
        facts,
        percentiles=dataclasses.replace(ladder, rungs=rungs, minimum=low, maximum=high),
        empty_edges=(),
        integer_valued=True,
    )


