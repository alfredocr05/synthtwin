def _pieces(cells: "list[int]") -> "tuple[generation._Piece, ...]":
    out: "list[generation._Piece]" = []
    first = 0
    for size in cells:
        out += [generation._Piece(first, size, None, False, None, False, generation._BAND_POSITIVE, True, True, 0)]
        first = first + size
    return tuple(out)


