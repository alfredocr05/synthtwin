def test_case_1_red_with_the_longest_run_divided_inside_the_top_piece(few, monkeypatch: pytest.MonkeyPatch) -> None:
    """MUTANT (ii): G5.2a step 3's division of the longest run and the ascending fill in place of item 3a, no ceiling.

    A within-column fact lost: the walls keep every band total, and half
    the threes are lifted onto four, every stratum above them by one.
    """
    _folder, switched = few
    monkeypatch.setattr(generation, "_l0_free_points", lambda facts, piece, values, lowest, highest, limit: limit)

    def divided(facts, piece, lengths, values, wanted, lowest, highest, ends=None):  # type: ignore[no-untyped-def]
        # the longest run divided, and G6.5a's ascending fill: each stratum
        # takes the next whole number up from the piece's first value
        sizes = list(lengths)
        held = list(values)
        for _step in range(wanted):
            sizes, held = generation._split_widest(sizes, held)
        return sizes, [float(held[0]) + step for step in range(len(sizes))], 0

    monkeypatch.setattr(generation, "_l0_gap_strata", divided)
    held = _at_each_value(generation.generate_held(switched.loaded, 0), switched, "count")
    top = sum(held[value] for value in held if value and float(value) >= 3)
    assert held["3"] <= 0.55 * top


