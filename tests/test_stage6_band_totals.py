def _blank_book(folder: pathlib.Path, rows: int, empties: int) -> pathlib.Path:
    strings = ["a", "b", "c", "x", "y", "z"]
    letters = "ABC"
    draw = random.Random(13)
    places = set(range(5, rows - 5, max(1, (rows - 10) // empties)))
    places = set(sorted(places)[:empties])
    body = [(1, [workbooks.cell(f"{letters[k]}1", str(k), "s") for k in range(3)])]
    for row in range(rows):
        number = row + 2
        if row in places:
            body += [(number, [workbooks.cell(f"{letters[k]}{number}", "", "", workbooks.HEADER_STYLE) for k in range(3)])]
            continue
        body += [(number, [
            workbooks.cell(f"A{number}", f"{draw.randint(1, 90)}"),
            workbooks.cell(f"B{number}", f"{round(draw.gauss(100, 10), 1)}"),
            workbooks.cell(f"C{number}", str(3 + draw.randint(0, 2)), "s"),
        ])]
    data = workbooks.package([
        ("[Content_Types].xml", workbooks._content_types(1, True, False, False)),
        ("_rels/.rels", workbooks._root_rels()),
        ("xl/workbook.xml", workbooks._workbook([("Data", "")])),
        ("xl/_rels/workbook.xml.rels", workbooks._workbook_rels(1, True)),
        ("xl/styles.xml", workbooks._styles()),
        ("xl/sharedStrings.xml", workbooks._shared_strings(strings)),
        ("xl/worksheets/sheet1.xml", workbooks.sheet(body, dimension=f"A1:C{rows + 1}")),
    ])
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / "book.xlsx"
    path.write_bytes(data)
    return path


def _book_back(folder: pathlib.Path, loaded: contract.Profile, twin: generation.Twin) -> "dict[str, object]":
    members = sheetwriting.workbook_members(loaded, twin)
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        for name, text in members:
            archive.writestr(name, text)
    out = folder / "twin.xlsx"
    out.write_bytes(buffer.getvalue())
    back = reading.read_table(str(out), small_cell_floor=1)
    return profile.build_document(back, taxonomy.Settings(small_cell_floor=1), [], [], [])


