# -- EACH BAND MET EXACTLY AT 20,000 ROWS ----------------------------------


def test_every_band_holds_its_published_count_at_twenty_thousand_rows(clinic) -> None:
    folder, switched = clinic
    published = {entry["column"]: entry["totals"] for entry in switched.statistical["ladder"]}
    roles = {column.name: column.statistical_type for column in switched.loaded.columns}
    twin = generation.generate_held(switched.loaded, 0)
    found = _read_back(folder, switched, twin)
    checked = set()
    for name in found:
        if roles[name] in ("count", "continuous", "datetime", "time_of_day"):
            assert _rows_off(found[name], published[name]) == 0, (name, found[name], published[name])
            checked |= {roles[name]}
    assert checked == {"count", "continuous", "datetime", "time_of_day"}
    # ...every eligible column laid with its band totals: no rule B3 and
    # no stratum the last guard had to move.
    assert [d for d in twin.deviations if d.fact == "band totals"] == []
    # The twin made without L0 misses them, which is why the layer exists.
    bare = _read_back(folder, switched, generation.generate_held(switched.plain, 0))
    assert sum(_rows_off(bare[name], published[name]) for name in bare if roles[name] != "binary") > 0


