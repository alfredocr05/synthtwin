"""Layer L0 built: every eligible column meets its L0 band totals (lane BT, plan P4-D429; method G4.2a, G4.2b, G5.7, G7.3l, G7A.4d, G12.15).

THE GATE OF LANE BT. Stage 6's layer L0 is built behind the switch no
shipped command sets (`contract.load_profile(..., chain=True)`): every
description a shipped command loads is laid out byte for byte as
before. This file holds:

- EACH BAND MET EXACTLY at 20,000 rows on a count, a continuous, a
  date and two clock columns of the product's own twin, read back the
  way the profile reads them (`chain.read_column`), against the twin
  made without L0, which misses them;
- the method's cases (G14.3a) where they turn on the construction: the
  count of few values with one rare high value, the share over pieces,
  the eligible gap, the word budget kept, a band of a finer width, a
  band the census does not name, the clock's halves and knots;
- THE RESERVATION of records holding nothing, in a text file and in a
  workbook, by spelling and by class;
- THE INTERFACE G16 calls, `cells_by_band`: its groups, sizes, order and
  cells, a label column's groups by level;
- the switch off: a description with no ladder is generated byte for
  byte as before;
- THE VALUE PASSES INSIDE THEIR PIECES (G5.7f): the push of G6.5a on
  a column of record numbers every one different;
- ONE MUTANT RED PER RULE: a band one row off, the old single-cell
  exchange, a within-column fact lost (the division and lift of
  G5.2a step 3 kept inside the top piece), the push walking its sign
  band, each red here.

Every table is invented here; the key is a fixed test key.
"""

