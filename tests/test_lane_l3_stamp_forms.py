def test_h4_the_letter_takes_no_place_in_the_room() -> None:
    """H4: a stamp's room counts its figures and its marker word, never its `T`.

    `%%%%-%%-%%@%%:%%` holds 10^12 spellings, not 26 times that; with a
    marker written straight on, twice its head's. Mutant: the letter
    counted as one of 26 overstates the room 26 times, and allocation then
    gives the form more stand-ins than it can write (lane L2's Codex item 3).
    """
    assert generation._form_room("%%%%-%%-%%@%%:%%") == 10 ** 12
    assert generation._form_room("%%%%-%%-%% %:%%@@") == 2 * 10 ** 11
    assert generation._form_room("%%%%-%%-%%&%:%% &&") == 2 * 10 ** 11
    assert generation._form_room("@%%.%") == 26000
    # Nor its zone, always `Z` (skeptic 2 of L3, item 2; mutant: the zone
    # counted as one of 26).
    assert generation._form_room("%%%%-%%-%%@%%:%%:%%@") == 10 ** 14
    assert generation._form_room("%%%%-%%-%%&%%:%%:%%.%%%&") == 10 ** 17
    assert generation._form_room("%%%%-%%-%%@%%:%%-%%:%%") == 10 ** 16


