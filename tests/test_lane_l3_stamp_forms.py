@pytest.mark.parametrize("form", sorted(set(_STAMPS.values())))
def test_h4_a_stamp_form_is_filled_with_its_letter_its_marker_word_and_its_gaps(form: str) -> None:
    """H4: 3,000 spellings of each stamp form, all different, each wearing the form.

    The letter between the date and the clock is `T` (`t` in the lower-case
    key), a marker is a word, each gap stands as the form holds it -- U+202F
    never a plain space -- and every spelling wears the form it was filled
    from; `_form_room` and `_form_steps` agree with the oracle's, and
    `_filled_form` with the oracle's `filled_form`. Mutants (below): the
    marker and the letter filled letter by letter; the letter counted as one
    of 26 in the room.
    """
    oracle = _oracle_module()
    filled_form = oracle["filled_form"]
    form_room = oracle["form_room"]
    form_steps = oracle["form_steps"]
    stamp_zone = oracle["stamp_zone"]
    assert callable(filled_form) and callable(form_room) and callable(form_steps) and callable(stamp_zone)
    for key in (form, parsing.lower_case_form(form)):
        if not key:
            continue
        spellings = [generation._filled_form(key, step) for step in range(3000)]
        assert len(set(spellings)) == 3000
        for spelling in spellings:
            assert parsing.shape_form(spelling) == form, (key, spelling)
            if "@" in key or "&" in key:
                assert re.search(r"(T|t)[0-9]|(AM|PM|am|pm|A\.M\.|P\.M\.|a\.m\.|p\.m\.)$", spelling), spelling
        if "&" in key:
            assert all(spelling == spelling.lower() for spelling in spellings)
        assert spellings[:200] == [filled_form(key, step) for step in range(200)]
        assert generation._form_room(key) == form_room(key)
        assert generation._form_steps(key) == form_steps(key)
        letter = parsing.stamp_key_parts(key)
        assert letter is not None
        if letter[2] >= 0:
            assert {spelling[letter[2]] for spelling in spellings} == {"t" if "&" in key else "T"}
        zone = parsing.stamp_key_zone_at(key)
        assert zone == stamp_zone(key)
        if zone >= 0:
            assert {spelling[zone] for spelling in spellings} == {"z" if "&" in key else "Z"}
        if NARROW in key:
            assert all(NARROW in spelling and spelling.count(" ") == key.count(" ") for spelling in spellings)


