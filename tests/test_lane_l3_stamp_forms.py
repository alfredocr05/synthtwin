def _stamp(draw: random.Random, spelling: str) -> str:
    """One made-up stamp of one battery spelling."""
    month = draw.randrange(1, 13)
    day = draw.randrange(1, 29)
    hour = draw.randrange(1, 13)
    minute = draw.randrange(60)
    word = ("AM", "PM")[draw.randrange(2)]
    if spelling == "iso-space":
        return f"2024-{month:02d}-{day:02d} {hour + 11:02d}:{minute:02d}"
    if spelling == "iso-am":
        return f"2024-{month:02d}-{day:02d} {hour}:{minute:02d} {word}"
    if spelling == "us-glued":
        return f"{month:02d}/{day:02d}/2024 {hour}:{minute:02d}{word}"
    if spelling == "us-narrow":
        return f"{month}/{day}/2024 {hour}:{minute:02d}:{draw.randrange(60):02d}{NARROW}{word}"
    if spelling == "dmy-fraction":
        return f"{day:02d}/{month:02d}/2024 {hour + 11:02d}:{minute:02d}:{draw.randrange(60):02d}.{draw.randrange(1000):03d}"
    return f"2024-{month:02d}-{day:02d}T{hour}:{minute:02d} {word}"


_SPELLINGS = ("iso-space", "iso-am", "us-glued", "us-narrow", "dmy-fraction", "iso-t-am")
_SHAPES = {
    "iso-space": r"\d{4}-\d{2}-\d{2} \d{2}:\d{2}",
    "iso-am": r"\d{4}-\d{2}-\d{2} \d{1,2}:\d{2} (AM|PM)",
    "us-glued": r"\d{2}/\d{2}/\d{4} \d{1,2}:\d{2}(AM|PM)",
    "us-narrow": r"\d{1,2}/\d{1,2}/\d{4} \d{1,2}:\d{2}:\d{2}" + NARROW + "(AM|PM)",
    "dmy-fraction": r"\d{2}/\d{2}/\d{4} \d{2}:\d{2}:\d{2}\.\d{3}",
    "iso-t-am": r"\d{4}-\d{2}-\d{2}T\d{1,2}:\d{2} (AM|PM)",
}


def _cells(role: str, spelling: str) -> "list[str]":
    draw = random.Random(393)
    if role == "labels":
        pool = [_stamp(draw, spelling) for _value in range(40)]
        return [
            ("pending", "unknown")[row % 2] if row % 33 == 7 else pool[min(int(draw.paretovariate(1.0)) - 1, 39)]
            for row in range(600)
        ]
    cells = []
    for row in range(400):
        if role != "clean" and row % 33 == 7:
            cells += [("pending", "unknown")[row % 2]]
            continue
        cells += [_stamp(draw, spelling)]
    return cells


@pytest.mark.parametrize("floor", (2, 11, 36))
@pytest.mark.parametrize("role", ("free", "labels", "codes", "clean"))
def test_h5_every_stamp_description_loads_generates_and_validates(
    tmp_path: pathlib.Path, floor: int, role: str
) -> None:
    """H5: the producer-always-loads battery over the stamp spellings.

    Six spellings (ISO with a space, with a gap and a marker, `T` and a
    marker; month first with a marker written straight on and with U+202F;
    day first to the millisecond), beside rare words, as labels, as declared
    codes and alone, at floors 2, 11 and 36: every description loads,
    generates, and validates against its twin and its table with exit 0;
    wherever a stamp form is published, every twin cell that is a stamp is
    written in its source's shape, `T` and marker word included, and no
    twin cell writes the other gap before a marker.
    """
    for spelling in _SPELLINGS:
        cells = _cells(role, spelling)
        block, written, twin_exit, table_exit = _round(
            tmp_path / spelling, cells, floor, coded=role == "codes"
        )
        assert (twin_exit, table_exit) == (0, 0), (spelling, block.get("role"))
        forms = block.get("shape_forms") or {}
        assert isinstance(forms, dict)
        if forms:
            shape = re.compile(_SHAPES[spelling])
            stamps = [cell for cell in written if parsing._stamp_cell_gaps(cell) is not None]
            assert stamps and all(shape.fullmatch(cell) for cell in stamps), (spelling, stamps[:3])
        other = " " if spelling == "us-narrow" else NARROW
        assert not [cell for cell in written if other + "AM" in cell or other + "PM" in cell]


