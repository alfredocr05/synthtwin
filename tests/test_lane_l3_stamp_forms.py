def test_h7_at_most_two_stamp_reads_per_form_asked_and_none_for_a_plain_short_cell(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """H7 (MACHINE-FREE): the census's stamp reads are counted, not timed.

    `taxonomy.profile_column` over N stamps beside rare words (N = 1,000,
    free text, and 10,000, a long tail whose published levels are counted
    once more) asks `_stamp_cell_gaps` at most twice per call of
    `shape_form` -- once for the gap before a marker, once for the stamp's
    form -- and `shape_form` at most twice per cell; each read covers at
    most 32 characters and builds no set. A column of 10,000 codes `A12-3`
    beside the same words, no longer than 24 characters, holding no space
    and ending in no marker's last character, asks none. Mutant: a read
    asked of every cell is counted on the codes.
    """
    asked = {"n": 0, "shape": 0}
    read = parsing._stamp_cell_gaps
    shape = parsing.shape_form

    def counted(text: str) -> "tuple[int, int, int, int] | None":
        asked["n"] += 1
        return read(text)

    def shape_counted(text: str) -> str:
        asked["shape"] += 1
        return shape(text)

    monkeypatch.setattr(parsing, "_stamp_cell_gaps", counted)
    monkeypatch.setattr(parsing, "shape_form", shape_counted)
    for rows in (1000, 10000):
        draw = random.Random(rows)
        cells = [
            "pending" if row % 33 == 7
            else f"2024-01-{draw.randrange(1, 29):02d} {draw.randrange(1, 13)}:{draw.randrange(60):02d} {('AM', 'PM')[row % 2]}"
            for row in range(rows)
        ]
        asked["n"] = 0
        asked["shape"] = 0
        taxonomy.profile_column("seen_at", 1, cells, rows, taxonomy.Settings())
        assert rows - rows // 33 <= asked["n"] <= 2 * asked["shape"] <= 4 * rows
    codes = ["pending" if row % 33 == 7 else f"A{row % 90 + 10}-{row % 7}" for row in range(10000)]
    asked["n"] = 0
    asked["shape"] = 0
    taxonomy.profile_column("seen_at", 1, codes, 10000, taxonomy.Settings())
    assert asked["shape"] >= 10000
    assert asked["n"] == 0


