# -- H3: nothing else moves -----------------------------------------------------


def _shape_form_before_l3(text: str) -> str:
    """`parsing.shape_form` as 7d27335 wrote it: lane L2's gap and no stamp."""
    if not text or len(text) > parsing.SHAPE_FORM_LIMIT:
        return ""
    gap = parsing._clock_meridiem_gap_at(text)
    form = ""
    figures = letters = marks = 0
    for place, character in enumerate(text):
        if place == gap:
            form += character
            marks = 1
            continue
        if character in (parsing.SHAPE_DIGIT, parsing.SHAPE_LETTER):
            return ""
        if "0" <= character <= "9":
            form += parsing.SHAPE_DIGIT
            figures = 1
        elif "a" <= character <= "z" or "A" <= character <= "Z":
            form += parsing.SHAPE_LETTER
            letters = 1
        elif character in parsing.SHAPE_MARKS:
            form += character
            marks = 1
        else:
            return ""
    return form if figures + letters + marks >= 2 else ""


def test_h3_every_cell_that_is_no_stamp_keeps_its_form() -> None:
    """H3: 80,000 seeded cells over figures, letters, marks and gaps.

    Every cell that is no stamp (`parsing._stamp_cell_gaps` None) has exactly
    the form it had on 7d27335, and so has every stamp that held neither a
    space nor a gap after a date nor more than 24 characters (a `T` stamp,
    `2024-01-05T09:15`); the sample held cells of every kind. Mutant: the
    stamp rule taking a cell it should not would move one.
    """
    draw = random.Random(393)
    alphabet = "0123456789-/:.TAMpm " + NARROW + "x#"
    dates = ("2024-01-05", "1/5/2024", "01/05/2024", "2024/01/05", "05.01.2024", "2024-1-05", "2024-01/05", "20240105")
    moved = 0
    stamps = 0
    others = 0
    for _cell in range(80000):
        cell = "".join(draw.choice(alphabet) for _place in range(draw.randrange(1, 30)))
        if draw.randrange(3) == 0:
            cell = (
                draw.choice(dates)
                + draw.choice((" ", "T", "  ", NARROW, ""))
                + f"{draw.randrange(24)}:{draw.randrange(60):02d}"
                + draw.choice(("", ":30", ":30.25", ".5"))
                + draw.choice(("", " AM", "pm", NARROW + "PM", " Am", " x", "Z"))
            )
        if parsing._stamp_cell_gaps(cell) is not None:
            stamps += 1
            assert parsing.shape_form(cell) != ""
            if not parsing._shaped_since_stamps(cell):
                assert parsing.shape_form(cell) == _shape_form_before_l3(cell)
            continue
        others += 1
        if parsing.shape_form(cell) != _shape_form_before_l3(cell):
            moved += 1
    assert moved == 0
    assert stamps > 3000 and others > 50000


